import { test, expect, type Page } from "@playwright/test"

test.beforeEach(async ({ page, request }) => {
  await request.post("/__fixture/reset")
  await page.route("**/*", route => {
    const url = new URL(route.request().url())
    return url.hostname === "127.0.0.1" ? route.continue() : route.abort("blockedbyclient")
  })
  await page.goto("/")
  await expect(page.getByLabel("Mission document", { exact: true })).toContainText("neighborhood gardens")
})

async function generate(page: Page) {
  await page.getByRole("button", { name: "AI document assistance", exact: true }).click()
  await expect(page.getByRole("button", { name: /25 credits maximum/ })).toBeVisible()
  await page.getByRole("textbox", { name: "Ask AI about this document" }).fill("Make this mission more concrete.")
  await page.getByRole("button", { name: "Generate document proposal" }).click()
  await expect(page.getByRole("button", { name: "Apply to editor", exact: true })).toBeVisible()
}

test("review, revise, apply, privately save and reopen the acknowledged draft", async ({ page, request }) => {
  const errors: string[] = []
  page.on("pageerror", error => errors.push(error.message))
  await generate(page)
  const assistance = page.getByRole("region", { name: "AI document assistance" })
  await page.getByRole("button", { name: "Compare original" }).click()
  await expect(assistance).toContainText("We support neighborhood gardens.")
  await expect(page.getByLabel("Mission document", { exact: true })).not.toContainText("welcoming")
  await page.getByRole("button", { name: "Revise", exact: true }).click()
  const composer = page.getByRole("textbox", { name: "Ask AI about this document" })
  await expect(composer).toBeFocused()
  await composer.fill("Emphasize growing together.")
  await page.getByRole("button", { name: "Generate document proposal" }).click()
  await expect(assistance).toContainText("thriving community gardens together")
  await request.post("/__fixture/control", { data: { delaySave: 500 } })
  await page.getByRole("button", { name: "Apply to editor", exact: true }).click()
  await expect(page.getByRole("button", { name: "Publish", exact: true })).toBeDisabled()
  await expect(assistance.getByRole("status")).not.toHaveText("Saved")
  await expect(page.getByTestId("editor-state")).toHaveText("Saved · Private")
  await expect(assistance.getByRole("status")).toHaveText("Saved")
  let state = await (await request.get("/__fixture/state")).json()
  expect(state.saves).toBe(1)
  expect(state.generations).toBe(2)
  expect(state.runs[1].revisionSourceRunId).toBe(state.runs[0].id)
  expect(state.section.isPublic).toBe(false)
  await page.reload()
  await expect(page.getByLabel("Mission document", { exact: true })).toContainText("thriving community gardens together")
  await page.getByRole("button", { name: "AI document assistance", exact: true }).click()
  await expect(assistance.getByRole("status")).toHaveText("Saved")
  await expect(page.getByRole("button", { name: "Apply to editor", exact: true })).toHaveCount(0)
  state = await (await request.get("/__fixture/state")).json()
  expect(state.saves).toBe(1)
  expect(errors).toEqual([])
  await page.screenshot({ path: "/tmp/workspace-ai-document-light.png", fullPage: true, animations: "disabled" })
  await page.evaluate(() => document.documentElement.classList.add("dark"))
  await page.screenshot({ path: "/tmp/workspace-ai-document-dark.png", fullPage: true, animations: "disabled" })
})

test("typing during save is retained and saved after the first acknowledgment", async ({ page, request }) => {
  await generate(page)
  await request.post("/__fixture/control", { data: { delaySave: 1200 } })
  await page.getByRole("button", { name: "Apply to editor", exact: true }).click()
  await expect(page.getByTestId("editor-state")).toContainText("Saving")
  await page.getByLabel("Mission document", { exact: true }).fill("We equip neighbors to create welcoming community gardens. Edited while saving.")
  await expect.poll(async () => (await (await request.get("/__fixture/state")).json()).section.content,
    { timeout: 15_000 }).toContain("Edited while saving.")
  await expect(page.getByTestId("editor-state")).toHaveText("Saved · Private")
  await expect(page.getByRole("region", { name: "AI document assistance" }).getByRole("status")).toHaveText("Applied previously")
  await page.reload()
  await expect(page.getByLabel("Mission document", { exact: true })).toContainText("Edited while saving.")
})

test("a lost save reply recovers the receipt without another canonical write", async ({ page, request }) => {
  await generate(page)
  await request.post("/__fixture/control", { data: { dropSaveReply: true } })
  await page.getByRole("button", { name: "Apply to editor", exact: true }).click()
  await expect.poll(async () => (await (await request.get("/__fixture/state")).json()).saves).toBe(1)
  await page.reload()
  await expect(page.getByLabel("Mission document", { exact: true })).toContainText("welcoming community gardens")
  await expect(page.getByTestId("editor-state")).toHaveText("Saved · Private")
  await page.getByRole("button", { name: "AI document assistance", exact: true }).click()
  await expect(page.getByRole("region", { name: "AI document assistance" }).getByRole("status")).toHaveText("Saved")
  expect((await (await request.get("/__fixture/state")).json()).saves).toBe(1)
})

test("a collaborator's newer save is not overwritten and the proposal remains available", async ({ page, request }) => {
  await generate(page)
  await request.post("/__fixture/collaborator")
  await page.getByRole("button", { name: "Apply to editor", exact: true }).click()
  await expect(page.getByText("This document changed. Reopen it before saving.", { exact: true }).first()).toBeVisible()
  await expect(page.getByTestId("editor-state")).toContainText("Unsaved")
  const state = await (await request.get("/__fixture/state")).json()
  expect(state.saves).toBe(0)
  expect(state.section.content).toContain("collaborator saved a newer mission")
  await expect(page.getByRole("region", { name: "AI document assistance" })).toContainText("welcoming community gardens")
})

test("failed revision retains its input and recovers the earlier draft after reload", async ({ page, request }) => {
  await generate(page)
  await page.getByRole("button", { name: "Revise", exact: true }).click()
  await request.post("/__fixture/control", { data: { failGeneration: true } })
  const composer = page.getByRole("textbox", { name: "Ask AI about this document" })
  await composer.fill("Keep the original focus.")
  await page.getByRole("button", { name: "Generate document proposal" }).click()
  await expect(page.getByRole("button", { name: "Previous draft" })).toBeVisible()
  await expect(composer).toHaveValue("Keep the original focus.")
  await page.reload()
  await page.getByRole("button", { name: "AI document assistance", exact: true }).click()
  await page.getByRole("button", { name: "Previous draft" }).click()
  await expect(page.getByRole("region", { name: "AI document assistance" })).toContainText("welcoming community gardens")
  await expect(page.getByRole("button", { name: "Apply to editor", exact: true })).toBeEnabled()
})

