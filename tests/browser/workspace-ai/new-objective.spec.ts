test("anchored chat keeps its height while panning and fits a smaller screen", async ({ page }) => {
  await page.emulateMedia({ reducedMotion: "reduce" })
  await setup(page, false)
  await page.goto("/?revisions&new-objective&visible-placement")
  const input = page.getByRole("textbox", { name: "Plan an objective or search Particles" })
  await input.fill("Open a community garden")
  await input.press("Enter")
  await generate(page)
  const chat = page.locator('[data-workspace-canvas-chat="true"]')
  await expect(page.getByRole("button", { name: "Minimize chat", exact: true })).toBeVisible()
  await expect.poll(() => chat.evaluate(el => el.style.getPropertyValue("--workspace-chat-panel-height")) ).toBe("560px")
  const initial = (await chat.boundingBox())!
  await page.mouse.move(1040, 780)
  await page.mouse.down()
  await page.mouse.move(1040, 430, { steps: 12 })
  await page.mouse.up()
  await expect.poll(async () => (await chat.boundingBox())!.y).toBeLessThan(initial.y - 300)
  expect((await chat.boundingBox())!.height).toBeCloseTo(initial.height, 0)
  await page.mouse.move(1040, 430)
  await page.mouse.down()
  await page.mouse.move(1040, 780, { steps: 12 })
  await page.mouse.up()
  await expect.poll(async () => (await chat.boundingBox())!.y).toBeCloseTo(initial.y, 0)
  expect((await chat.boundingBox())!.height).toBeCloseTo(initial.height, 0)
  await page.setViewportSize({ width: 1100, height: 600 })
  await expect.poll(() => chat.evaluate(el => parseFloat(el.style.getPropertyValue("--workspace-chat-panel-height")))).toBeLessThan(500)
  const smaller = (await chat.boundingBox())!
  expect(smaller.height).toBeLessThan(600)
  await page.mouse.move(1040, 500)
  await page.mouse.down()
  await page.mouse.move(1040, 300, { steps: 8 })
  await page.mouse.up()
  await expect.poll(async () => (await chat.boundingBox())!.y).toBeLessThan(smaller.y - 150)
  expect((await chat.boundingBox())!.height).toBeCloseTo(smaller.height, 0)
})

