  await first.getByRole("checkbox", { name: "Arrange volunteers" }).uncheck()
  await expect(first.getByText("This path ends here.")).toBeVisible()
  await expect(page.getByRole("button", { name: "Remove item 2", exact: true })).toBeEnabled()
  const second = page.getByRole("group", { name: "Next items for outcome 2", exact: true })
  const destination = second.getByRole("checkbox", { name: "Arrange volunteers" })
  await destination.focus(); await destination.press("Space")
  await expect(page.getByRole("button", { name: "Remove item 2", exact: true })).toBeDisabled()
  await page.evaluate(() => window.dispatchEvent(new Event("focus")))
  // Authorized rechecks remount disclosures; the parent draft must survive.
  await page.locator("summary").filter({ hasText: "Branches (2)" }).click()
