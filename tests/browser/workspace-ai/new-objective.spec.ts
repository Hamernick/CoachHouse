import { expect, test, type Page } from "@playwright/test"
import type { ResearchRequest, ResearchResult } from "../../../src/features/workspace-ai/research-types"

async function setup(page: Page, open = true, branches = false) {
  const runs = new Map<string, ResearchResult>()
  await page.route("**/api/workspace-ai/research", async route => {
    const request = route.request().postDataJSON() as ResearchRequest
    expect(request.target).toMatchObject({ mode: "new_objective", canvasId: null, revision: 0 })
    expect(request.target).not.toHaveProperty("objectiveId")
    const result: ResearchResult = { runId: request.id, target: request.target, title: "Open community garden", summary: "Confirm a site before arranging volunteers.",
      questions: [], decisions: [], removeReferences: [], sources: [], items: [
        { key: "site", title: "Confirm the site", kind: "note", description: "Check access and availability.", referenceId: null, evidenceIds: [], dependsOn: [] },
        { key: "volunteers", title: "Arrange volunteers", kind: "note", description: "Invite the team after site confirmation.", referenceId: null, evidenceIds: [], dependsOn: ["site"] },
      ] }
    if (branches) {
      result.items[0].kind = "decision"
      result.items[1].dependsOn = []
      result.decisions = [{ itemKey: "site", outcomes: [{ key: "yes", label: "Available", next: ["volunteers"] }, { key: "no", label: "Unavailable", next: [] }] }]
    }
    runs.set(request.id, result)
    await page.evaluate(result => localStorage.setItem(`revision-result:${result.runId}`, JSON.stringify(result)), result)
    await route.fulfill({ json: { run: { version: 1, resultRevision: 1, applicability: "review_required", id: result.runId, credits: null, status: "succeeded", result } } })
  })
  await page.route("**/__fixture/revision-read", route => route.fulfill({ json: { run: { version: 1, resultRevision: 1, applicability: "review_required", id: route.request().postDataJSON().id, credits: null, status: "succeeded", result: runs.get(route.request().postDataJSON().id) } } }))
  await page.route("**/__fixture/revision-history", route => route.fulfill({ json: { runs: [...runs.values()].map(result => ({ id: result.runId, status: "succeeded", created_at: "2026-10-30T10:00:00Z" })) } }))
  await page.goto("/?revisions&new-objective")
  if (open) {
    await page.getByRole("button", { name: "Plan with AI", exact: true }).click()
    await expect(page.getByRole("textbox", { name: "Research request" })).toBeFocused()
  }
  return runs
}
const state = async (page: Page) => JSON.parse(await page.getByTestId("revision-state").textContent() ?? "{}")
async function generate(page: Page) {
  await page.getByRole("textbox", { name: "Research request" }).fill("Open a community garden")
  await page.getByRole("button", { name: "Generate plan", exact: true }).click()
  await expect(page.getByRole("button", { name: "Add proposal", exact: true })).toBeEnabled()
}

test("blank board previews, recovers and saves one pending plan; owner reviews and edits", async ({ page }) => {
  const runs = await setup(page)
  expect((await state(page)).particles).toEqual([])
  await generate(page)
  expect((await state(page)).particles).toEqual([])
  await expect(page.getByText("After: Confirm the site")).toBeVisible()
  await page.reload()
  await page.getByRole("button", { name: "Plan with AI", exact: true }).click()
  await expect(page.getByRole("button", { name: "Add proposal", exact: true })).toBeEnabled()
  expect(runs.size).toBe(1)
  await page.getByRole("button", { name: "Add proposal", exact: true }).click()
  await expect(page.getByRole("form", { name: "Plan a new objective" })).toHaveCount(0)
  await expect(page.getByRole("button", { name: "Plan with AI", exact: true })).toBeFocused()
  const saved = await state(page), objective = saved.particles.find((p: { type: string }) => p.type === "objective")
  expect(saved.particles).toHaveLength(3)
  expect(objective.data.planning.plans).toEqual([])
  expect(objective.data.planning.proposals[0].status).toBe("pending")
  await page.reload()
  expect((await state(page)).particles).toHaveLength(3)
  const objectiveButton = page.getByRole("button", { name: "Open community garden Not started", exact: true })
  await objectiveButton.focus(); await objectiveButton.press("Enter")
  await page.getByRole("button", { name: "Accept Open community garden", exact: true }).click()
  await expect.poll(async () => (await state(page)).particles.find((p: { type: string }) => p.type === "objective").data.planning.plans.length).toBe(1)
  await page.getByRole("button", { name: "Options for Open community garden", exact: true }).first().click()
  await page.getByRole("menuitem", { name: "Rename", exact: true }).click()
  const title = page.getByRole("textbox", { name: "Plan title" })
  await title.fill("Garden opening")
  await title.press("Enter")
  await page.reload()
  expect((await state(page)).particles.find((p: { type: string }) => p.type === "objective").title).toBe("Garden opening")
  expect(runs.size).toBe(1)
})

