import { test, expect } from "@playwright/test"
test.beforeEach(async ({ page }) => {
  await page.route("**/*", route => new URL(route.request().url()).hostname === "127.0.0.1" ? route.continue() : route.abort())
})
test("explicitly assigns an allowance to the named organization and preserves usage filters", async ({ page }) => {
  await page.goto("/?credits&allowance")
  const allowance = page.getByRole("region", { name: "Subscription allowance", exact: true })
  await expect(allowance).toContainText("Fictional Organization")
  await expect(page.getByText("100 credits available")).toBeVisible()
  await page.getByRole("combobox", { name: "Usage task" }).click()
  await page.getByRole("option", { name: "Plans", exact: true }).click()
  await allowance.getByRole("button", { name: "Assign", exact: true }).click()
  await expect(allowance).toContainText("500 included credits/month")
  await expect(page.getByText("600 credits available")).toBeVisible()
  await expect(page.getByRole("combobox", { name: "Usage task" })).toContainText("Plans")
  await expect(page.locator("dt", { hasText: "Included" }).locator("+ dd")).toHaveText("500 / 500")
  await page.reload()
  await expect(allowance).toContainText("500 included credits/month")
  await expect(allowance.getByRole("button", { name: "Assign", exact: true })).toHaveCount(0)
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem("allowance-calls")!).length)).toBe(1)
})
test("uncertain confirmation retries the same assignment without another subscription charge", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto("/?credits&allowance&allowance-failure")
  await page.evaluate(() => document.documentElement.classList.add("dark"))
  const allowance = page.getByRole("region", { name: "Subscription allowance", exact: true })
  await allowance.getByRole("button", { name: "Assign", exact: true }).click()
  await expect(allowance.getByRole("alert")).toContainText("confirmation pending")
  await expect(page.getByText("100 credits available")).toBeVisible()
  await allowance.getByRole("button", { name: "Assign", exact: true }).click()
  await expect(page.getByText("600 credits available")).toBeVisible()
  const calls = await page.evaluate(() => JSON.parse(localStorage.getItem("allowance-calls")!))
  expect(calls).toHaveLength(2); expect(calls[0]).toEqual(calls[1])
  expect(await page.locator("main").evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  await page.screenshot({ path: "/tmp/workspace-credit-allowance-dark.png" })
})
