import { expect, test } from "@playwright/test"

test("dropdown date and time survive draft reopen and validate without submitting the host", async ({ page }) => {
  const errors: string[] = []
  page.on("pageerror", error => errors.push(error.message))
  await page.setViewportSize({ width: 320, height: 900 })
  await page.emulateMedia({ reducedMotion: "reduce" })
  await page.goto("/?form-controls")
  await page.getByRole("combobox", { name: "Question 1 type" }).click()
  await page.getByRole("option", { name: "Dropdown", exact: true }).click()
  await page.getByRole("button", { name: "Save draft", exact: true }).click()
  await expect(page.getByLabel("Draft saves")).toHaveText("1")
  await page.getByRole("button", { name: "Reopen draft" }).click()
  await expect(page.getByRole("combobox", { name: "Question 1 type" })).toHaveText("Dropdown")
  await page.getByRole("button", { name: "Preview", exact: true }).click()
  await page.getByRole("button", { name: "Check answers" }).click()
  const location = page.getByRole("combobox", { name: "Location (required)" })
  await expect(location).toBeFocused()
  await expect(location).toHaveAttribute("aria-invalid", "true")
  await location.press("Enter")
  await page.getByRole("option", { name: "South", exact: true }).click()
  await page.getByLabel(/^Day\s*\(required\)$/).fill("2028-02-29")
  const time = page.getByLabel(/^Time\s*\(required\)$/)
  await time.fill("02:30")
  await time.press("Enter")
  await expect(page.getByRole("group", { name: "Form preview" }).getByRole("status")).toHaveText("Answers look good. Nothing was submitted.")
  await expect(page.getByLabel("Draft saves")).toHaveText("1")
  await location.click()
  await page.getByRole("option", { name: "No selection", exact: true }).click()
  await page.getByRole("button", { name: "Check answers" }).click()
  await expect(location).toBeFocused()
  await expect(location).toHaveAttribute("aria-invalid", "true")
  await page.getByRole("button", { name: "Save draft", exact: true }).click()
  await expect(page.getByLabel("Draft saves")).toHaveText("2")
  // Rehearsal values do not persist with the definition.
  await page.getByRole("button", { name: "Reopen draft" }).click()
  await page.getByRole("button", { name: "Preview", exact: true }).click()
  await expect(page.getByLabel(/^Day\s*\(required\)$/)).toHaveValue("")
  await expect(time).toHaveValue("")
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  expect(errors).toEqual([])
})


test("duplicate and keyboard reorder keep identities, save/reopen, cancel and respect editing locks", async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 1000 })
  await page.emulateMedia({ reducedMotion: "reduce" })
  await page.goto("/?form-controls")
  const read = async () => JSON.parse(await page.getByLabel("Current definition").innerText()).questions as { id: string; label: string; options?: string[] }[]
  const original = await read()
  await page.getByRole("button", { name: "Duplicate question 1", exact: true }).click()
  await expect(page.getByRole("textbox", { name: "Question 2 label" })).toBeFocused()
  await page.getByRole("textbox", { name: "Question 2 label" }).fill("Second location")
  const copied = await read()
  expect(new Set(copied.map(q => q.id)).size).toBe(4)
  expect(copied[1].options).toEqual(["North", "South"])
  expect(copied[0]).toEqual(original[0])
  // Collapse before dragging; the separate handle does not toggle the editor.
  await page.getByRole("button", { name: /^2 Second location/ }).click()
  const handle = page.getByRole("button", { name: "Reorder question 2: Second location", exact: true })
  await handle.focus(); await page.keyboard.press("Space"); await page.keyboard.press("ArrowDown"); await page.keyboard.press("Space")
  await expect(page.getByRole("button", { name: "Reorder question 3: Second location", exact: true })).toBeFocused()
  expect((await read()).map(q => q.label)).toEqual(["Location", "Day", "Second location", "Time"])
  await page.keyboard.press("Space"); await page.keyboard.press("ArrowUp"); await page.keyboard.press("Escape")
  expect((await read()).map(q => q.id)).toEqual([copied[0].id, copied[2].id, copied[1].id, copied[3].id])
  await page.getByRole("button", { name: "Save draft", exact: true }).click()
  await page.getByRole("button", { name: "Reopen draft" }).click()
  expect((await read()).map(q => q.label)).toEqual(["Location", "Day", "Second location", "Time"])
  await page.getByRole("button", { name: "Toggle editing lock" }).click()
  await expect(page.getByRole("button", { name: "Duplicate question 1", exact: true })).toBeDisabled()
  await expect(page.getByRole("button", { name: "Reorder question 1: Location", exact: true })).toBeDisabled()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test("pointer drag reorders without expanding; outside drop and mid-drag lock cancel", async ({ page }) => {
  await page.goto("/?form-controls")
  await page.getByRole("button", { name: /^1 Location/ }).click()
  const before = await page.getByLabel("Current definition").innerText()
  const start = async () => {
    const box = await page.getByRole("button", { name: "Reorder question 1: Location", exact: true }).boundingBox()
    if (!box) throw new Error("Missing handle")
    await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2); await page.mouse.down()
    await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2 + 10, { steps: 3 })
  }
  await start(); await page.mouse.move(5, 5, { steps: 5 }); await page.mouse.up()
  expect(await page.getByLabel("Current definition").innerText()).toBe(before)
  await start()
  const end = await page.getByRole("button", { name: "Reorder question 3: Time", exact: true }).boundingBox()
  if (!end) throw new Error("Missing target")
  await page.mouse.move(end.x + end.width / 2, end.y + end.height / 2, { steps: 10 }); await page.mouse.up()
  await expect(page.getByRole("button", { name: "Reorder question 3: Location", exact: true })).toBeVisible()
  await expect(page.getByRole("textbox", { name: /Question .* label/ })).toHaveCount(0)
  const reordered = await page.getByLabel("Current definition").innerText()
  const lockedHandle = page.getByRole("button", { name: "Reorder question 3: Location", exact: true })
  const box = await lockedHandle.boundingBox()
  if (!box) throw new Error("Missing moved handle")
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2); await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2 - 10, { steps: 3 })
  await page.evaluate(() => window.dispatchEvent(new Event("fixture-lock-form")))
  await expect(lockedHandle).toBeDisabled()
  await page.mouse.up()
  expect(await page.getByLabel("Current definition").innerText()).toBe(reordered)
})

test("touch handle reorders while question content remains normally scrollable", async ({ browser }) => {
  const context = await browser.newContext({ viewport: { width: 320, height: 950 }, hasTouch: true, reducedMotion: "reduce" })
  const page = await context.newPage()
  try {
    await page.goto("http://127.0.0.1:3187/?form-controls")
    await page.getByRole("button", { name: /^1 Location/ }).tap()
    const start = await page.getByRole("button", { name: "Reorder question 1: Location", exact: true }).boundingBox()
    const end = await page.getByRole("button", { name: "Reorder question 3: Time", exact: true }).boundingBox()
    if (!start || !end) throw new Error("Missing touch handles")
    const client = await context.newCDPSession(page)
    const x = start.x + start.width / 2, y = start.y + start.height / 2
    await client.send("Input.dispatchTouchEvent", { type: "touchStart", touchPoints: [{ x, y }] })
    for (let step = 1; step <= 10; step++) {
      await client.send("Input.dispatchTouchEvent", { type: "touchMove", touchPoints: [{ x, y: y + (end.y + end.height / 2 - y) * step / 10 }] })
    }
    await client.send("Input.dispatchTouchEvent", { type: "touchEnd", touchPoints: [] })
    await expect(page.getByRole("button", { name: "Reorder question 3: Location", exact: true })).toBeVisible()
    expect(await page.getByRole("button", { name: /^3 Location/ }).evaluate(element => getComputedStyle(element).touchAction)).toBe("auto")
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  } finally { await context.close() }
})
