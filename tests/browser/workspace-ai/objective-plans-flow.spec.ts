import { test, expect, type Page } from "@playwright/test"
async function openObjective(page: Page) {
  await page.getByRole("button", { name: "Objectives", exact: true }).click()
  await page.getByRole("button", { name: "Launch a volunteer program", exact: true }).click()
}
async function newPlan(page: Page, title: string, steps: string[]) {
  await page.getByRole("button", { name: "Add to plan", exact: true }).click()
  await page.getByLabel("Plan name", { exact: true }).fill(title)
  for (const [index, step] of steps.entries()) {
    await page.getByRole("button", { name: "Add item", exact: true }).click()
    await page.getByLabel(`Item ${index + 1} title`, { exact: true }).fill(step)
  }
}
test.beforeEach(async ({ page }) => {
  await page.route("**/*", route => new URL(route.request().url()).hostname === "127.0.0.1" ? route.continue() : route.abort())
  await page.goto("/?objectives")
  await openObjective(page)
})
test("save a branched plan, synchronize checklist/tree, edit from tree and reopen", async ({ page }) => {
  await newPlan(page, "Volunteer launch", ["Confirm venue", "Host in person", "Host online"])
  await expect(page.getByRole("button", { name: "Connections", exact: true })).toHaveCount(0)
  await page.getByRole("button", { name: "Item 1 options", exact: true }).click()
  await page.getByRole("menuitem", { name: "Status", exact: true }).click()
  await page.getByRole("menuitemradio", { name: "Blocked", exact: true }).click()
  await page.getByRole("button", { name: "Save plan", exact: true }).click()
  // Connections remain saved data; the user removed their manual editor.
  await page.evaluate(() => {
    const data = JSON.parse(localStorage.getItem("objective-fixture")!)
    const plan = data.planning.plans[0]
    plan.edges = plan.stepIds.slice(1).map((target: string, index: number) => ({
      id: crypto.randomUUID(), source: plan.stepIds[0], target,
      label: index === 0 ? "Venue available" : "No venue",
    }))
    localStorage.setItem("objective-fixture", JSON.stringify(data))
  })
  await page.reload()
  await page.getByRole("button", { name: "Objectives", exact: true }).click()
  await page.getByRole("button", { name: "Launch a volunteer program", exact: true }).click()
  await expect(page.getByRole("dialog")).toHaveCount(0)
  await page.getByRole("button", { name: "Show Volunteer launch tree" }).click()
  await expect(page.locator(".react-flow__node-objectivePlanStep")).toHaveCount(3)
  await expect(page.locator(".react-flow__edge")).toHaveCount(2)
  await page.getByRole("button", { name: "Objectives", exact: true }).click()
  await page.getByRole("button", { name: "Volunteer launch 0/3", exact: true }).click()
  await page.getByRole("checkbox", { name: "Confirm venue", exact: true }).check()
  await expect(page.getByRole("checkbox", { name: "Complete Confirm venue", exact: true })).toBeChecked()
  await page.getByRole("button", { name: "Objectives", exact: true }).click()
  await page.getByRole("checkbox", { name: "Complete Host online", exact: true }).check()
  await page.getByRole("button", { name: "Edit plan for Host online", exact: true }).click()
  await page.getByLabel("Item 3 title", { exact: true }).fill("Host a virtual session")
  await page.getByRole("button", { name: "Save plan", exact: true }).click()
  await expect(page.getByRole("checkbox", { name: "Complete Host a virtual session", exact: true })).toBeChecked()
  await page.reload(); await openObjective(page)
  await page.getByRole("button", { name: "Volunteer launch 2/3", exact: true }).click()
  await expect(page.getByRole("checkbox", { name: "Host a virtual session", exact: true })).toBeChecked()
  await page.getByRole("button", { name: "Show Volunteer launch tree" }).click()
  await expect.poll(async () => (await page.locator(".react-flow__node-objectivePlanStep").first().boundingBox())?.y ?? 0).toBeGreaterThan(100)
  await page.screenshot({ path: "/tmp/workspace-objective-plans-tree.png" })
})
test("reuse a shared step without duplication, keep unrelated plans separate, discard edits", async ({ page }) => {
  await newPlan(page, "First plan", ["Shared preparation"])
  await page.getByRole("button", { name: "Save plan", exact: true }).click()
  await newPlan(page, "Related plan", [])
  await page.getByRole("combobox", { name: "Reuse saved item" }).click()
  await page.getByRole("option", { name: "Shared preparation", exact: true }).click()
  await page.getByRole("button", { name: "Save plan", exact: true }).click()
  await newPlan(page, "Independent plan", ["Unrelated task"])
  await page.getByRole("button", { name: "Save plan", exact: true }).click()
  await page.getByRole("button", { name: "Show First plan tree" }).click()
  await expect(page.locator(".react-flow__node-objectivePlanStep")).toHaveCount(1)
  await expect(page.locator(".react-flow__node")).toContainText("First plan · Related plan")
  await page.getByRole("button", { name: "Objectives", exact: true }).click()
  await page.getByRole("button", { name: "Show Independent plan tree" }).click()
  await expect(page.locator(".react-flow__node-objectivePlanStep")).toHaveCount(2)
  await expect(page.locator(".react-flow__edge")).toHaveCount(0)
  await page.getByRole("button", { name: "Objectives", exact: true }).click()
  await page.getByRole("button", { name: "Edit First plan plan", exact: true }).click()
  await page.getByLabel("Plan name", { exact: true }).fill("Unsaved plan title")
  await page.getByRole("button", { name: "Cancel", exact: true }).click()
  await expect(page.getByText("Discard unsaved plan changes?")).toBeVisible()
  await page.getByRole("button", { name: "Discard", exact: true }).click()
  await expect(page.getByRole("button", { name: "Show First plan tree" })).toBeVisible()
  await page.getByRole("button", { name: "Switch fixture organization" }).evaluate((button: HTMLButtonElement) => button.click())
  await expect(page.locator(".react-flow__node-objectivePlanStep")).toHaveCount(0)
})
test("plan editor fits narrow dark screens and preserves drafts on attempted dismissal", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ reducedMotion: "reduce", colorScheme: "dark" })
  await page.evaluate(() => document.documentElement.classList.add("dark"))
  await newPlan(page, "Community event", ["Confirm the venue and accessibility requirements"])
  const dialog = page.getByRole("region", { name: "New plan", exact: true })
  expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  await page.getByRole("button", { name: "Add item", exact: true }).click()
  await page.getByLabel("Item 2 title", { exact: true }).fill("Remove this draft item")
  await page.getByRole("button", { name: "Item 2 options", exact: true }).click()
  await page.getByRole("menuitem", { name: "Delete", exact: true }).click()
  await expect(page.getByLabel("Item 2 title", { exact: true })).toHaveCount(0)
  await page.getByLabel("Plan name", { exact: true }).focus()
  await page.keyboard.press("Escape")
  await expect(page.getByText("Discard unsaved plan changes?")).toBeVisible()
  await page.getByRole("button", { name: "Keep editing", exact: true }).click()
  await expect(page.getByLabel("Plan name", { exact: true })).toHaveValue("Community event")
  await page.screenshot({ path: "/tmp/workspace-objective-plan-editor-dark.png" })
})


test("rename a plan inline without replacing the objective list, then reload", async ({ page }) => {
  await newPlan(page, "Workshop plan", ["Keep existing work"])
  await page.getByRole("button", { name: "Save plan", exact: true }).click()
  await page.getByRole("button", { name: "Edit Workshop plan plan", exact: true }).click()
  await expect(page.getByRole("region", { name: "Edit plan", exact: true })).toHaveCount(0)
  await expect(page.getByRole("button", { name: "Launch a volunteer program", exact: true })).toBeVisible()
  await page.getByRole("textbox", { name: "Plan title", exact: true }).fill("Community workshop")
  await page.getByRole("button", { name: "Save title", exact: true }).click()
  await expect(page.getByRole("button", { name: "Community workshop", exact: true })).toBeVisible()
  await page.reload(); await openObjective(page)
  await page.getByRole("button", { name: "Community workshop", exact: true }).click()
  await expect(page.getByRole("checkbox", { name: "Keep existing work", exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Edit Community workshop plan", exact: true }).click()
  await page.getByRole("textbox", { name: "Plan title", exact: true }).fill("Unsaved change")
  await page.getByRole("textbox", { name: "Plan title", exact: true }).press("Escape")
  await expect(page.getByRole("button", { name: "Community workshop", exact: true })).toBeVisible()
  await expect(page.getByRole("button", { name: "Objectives", exact: true })).toHaveAttribute("aria-expanded", "true")
})
