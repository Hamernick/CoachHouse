import { test, expect } from "@playwright/test"
test.beforeEach(async ({ page }) => {
  await page.route("**/*", route => new URL(route.request().url()).hostname === "127.0.0.1" ? route.continue() : route.abort())
  await page.goto("/?credits")
})
test("sets and removes organization and member caps through one compact editor, preserving reload", async ({ page }) => {
  test.setTimeout(90_000)
  await page.getByRole("button", { name: "Spending limits", exact: true }).click()
  await page.getByLabel("Monthly credit limit", { exact: true }).fill("500")
  await page.getByRole("button", { name: "Save limit", exact: true }).click()
  await expect(page.getByRole("status")).toContainText("Limit saved")
  await expect(page.getByText("25 / 500 credits this month")).toBeVisible()
  await page.getByRole("combobox", { name: "Spending limit for" }).click()
  await page.getByRole("option", { name: "Fictional Teammate", exact: true }).click()
  await page.getByLabel("Monthly credit limit", { exact: true }).fill("0")
  await page.getByRole("button", { name: "Save limit", exact: true }).click()
  await expect(page.getByRole("status")).toContainText("Limit saved")
  await page.reload()
  await page.getByRole("button", { name: "Spending limits", exact: true }).click()
  await expect(page.getByLabel("Monthly credit limit", { exact: true })).toHaveValue("500")
  await page.getByRole("combobox", { name: "Spending limit for" }).click()
  await page.getByRole("option", { name: "Fictional Teammate", exact: true }).click()
  await expect(page.getByLabel("Monthly credit limit", { exact: true })).toHaveValue("0")
  await page.getByLabel("Monthly credit limit", { exact: true }).fill("")
  await page.getByRole("button", { name: "Save limit", exact: true }).click()
  await expect(page.getByRole("status")).toContainText("Limit saved")
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem("credit-limits")!).members[1].limit)).toBeNull()
  await page.setViewportSize({ width: 390, height: 844 }); await page.evaluate(() => document.documentElement.classList.add("dark"))
  expect(await page.locator("main").evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  await page.screenshot({ path: "/tmp/workspace-credit-limits-dark.png" })
})
test("a stale edit preserves typed value until explicit reload instead of overwriting another owner session", async ({ page }) => {
  await page.getByRole("button", { name: "Spending limits", exact: true }).click()
  await page.getByLabel("Monthly credit limit", { exact: true }).fill("100")
  await page.getByRole("button", { name: "Save limit", exact: true }).click()
  await expect(page.getByRole("status")).toContainText("Limit saved")
  await page.evaluate(() => { const limits = JSON.parse(localStorage.getItem("credit-limits")!); limits.organization.limit = 200; limits.organization.revision = crypto.randomUUID(); localStorage.setItem("credit-limits", JSON.stringify(limits)) })
  await page.getByLabel("Monthly credit limit", { exact: true }).fill("300")
  await page.getByRole("button", { name: "Save limit", exact: true }).click()
  await expect(page.getByRole("alert")).toContainText("Spending limit changed")
  await expect(page.getByLabel("Monthly credit limit", { exact: true })).toHaveValue("300")
  await page.getByRole("button", { name: "Reload limits", exact: true }).click()
  await expect(page.getByLabel("Monthly credit limit", { exact: true })).toHaveValue("200")
})
test("members get their own limit summary and owner path without editing controls", async ({ page }) => {
  await page.goto("/?credits&staff")
  await expect(page.getByText(/Ask your organization owner/)).toBeVisible()
  await expect(page.getByRole("button", { name: "Spending limits", exact: true })).toHaveCount(0)
})
