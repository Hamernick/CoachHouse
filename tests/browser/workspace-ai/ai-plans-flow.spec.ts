import { test, expect, type Page } from "@playwright/test"
async function open(page: Page) {
  await page.getByRole("button", { name: "Objectives", exact: true }).click()
  await page.getByRole("button", { name: "Launch a volunteer program", exact: true }).click()
  await page.getByRole("button", { name: "Plan with AI", exact: true }).click()
}
async function generate(page: Page, prompt = "Help plan our community event") {
  await page.getByLabel("What should the plan consider?", { exact: true }).fill(prompt)
  await page.getByRole("button", { name: "Generate proposal", exact: true }).click()
}
test.beforeEach(async ({ page }) => {
  await page.route("**/*", route => new URL(route.request().url()).hostname === "127.0.0.1" ? route.continue() : route.abort())
  await page.goto("/?objectives"); await open(page)
})
test("review, revise, apply once and edit the same canonical plan", async ({ page }) => {
  await generate(page)
  await expect(page.getByRole("heading", { name: "Community event proposal", exact: true })).toBeVisible()
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem("objective-fixture") || '{"planning":{"plans":[]}}').planning.plans.length)).toBe(0)
  await page.getByLabel("What should change?", { exact: true }).fill("Make it suitable for a small team")
  await page.getByRole("button", { name: "Revise proposal", exact: true }).click()
  await expect(page.getByRole("heading", { name: "Revised community event", exact: true })).toBeVisible()
  await page.getByRole("tab", { name: "Tree", exact: true }).click()
  await expect(page.getByRole("region", { name: "Plan with AI", exact: true }).locator(".react-flow__node-objectivePlanStep")).toHaveCount(3)
  await expect(page.getByRole("region", { name: "Plan with AI", exact: true }).locator(".react-flow__edge")).toHaveCount(2)
  await page.screenshot({ path: "/tmp/workspace-ai-plan-review.png" })
  await page.getByRole("region", { name: "Plan with AI", exact: true }).getByRole("button", { name: "Add plan", exact: true }).click()
  await expect(page.getByText("Plan saved. You can edit its steps in the checklist or tree.")).toBeVisible()
  await page.getByRole("button", { name: "Check status", exact: true }).click()
  await page.getByRole("region", { name: "Plan with AI", exact: true }).getByRole("button", { name: "Back", exact: true }).click()
  await page.getByRole("button", { name: "Show Revised community event tree", exact: true }).click()
  await expect(page.locator(".react-flow__node-objectivePlanStep")).toHaveCount(3)
  await page.getByRole("button", { name: "Objectives", exact: true }).click()
  await page.getByRole("button", { name: "Edit Revised community event plan", exact: true }).click()
  await page.getByLabel("Plan name", { exact: true }).fill("Our event plan")
  await page.getByRole("button", { name: "Save plan", exact: true }).click()
  await page.reload(); await open(page)
  await expect(page.getByText("Plan saved. You can edit its steps in the checklist or tree.")).toBeVisible()
  await page.getByRole("button", { name: "Undo adding plan", exact: true }).click()
  await expect(page.getByRole("region", { name: "Plan with AI", exact: true }).getByRole("alert")).toContainText("changed")
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem("objective-fixture")!).planning.plans.length)).toBe(1)
})
test("recovers a lost generation and application response, then undoes without duplicating", async ({ page }) => {
  await generate(page, "interrupt the fictional response")
  await expect(page.getByRole("alert")).toContainText("Connection interrupted")
  await page.reload(); await open(page)
  await expect(page.getByRole("heading", { name: "Community event proposal", exact: true })).toBeVisible()
  await page.evaluate(() => sessionStorage.setItem("lose-ai-apply-response", "true"))
  await page.getByRole("region", { name: "Plan with AI", exact: true }).getByRole("button", { name: "Add plan", exact: true }).click()
  await expect(page.getByRole("alert")).toContainText("Check status")
  await page.getByRole("button", { name: "Check status", exact: true }).click()
  await expect(page.getByText("Plan saved. You can edit its steps in the checklist or tree.")).toBeVisible()
  await page.getByRole("button", { name: "Undo adding plan", exact: true }).click()
  await expect(page.getByText("Plan removed. Your AI usage is unchanged.")).toBeVisible()
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem("objective-fixture")!).planning.plans.length)).toBe(0)
  await page.reload(); await open(page)
  await expect(page.getByText("Plan removed. Your AI usage is unchanged.")).toBeVisible()
})
test("narrow dark review preserves a prior proposal after a failed revision and discards privately", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 }); await page.emulateMedia({ reducedMotion: "reduce", colorScheme: "dark" }); await page.evaluate(() => document.documentElement.classList.add("dark"))
  await generate(page)
  await page.getByLabel("What should change?", { exact: true }).fill("fail revision")
  await page.getByRole("button", { name: "Revise proposal", exact: true }).click()
  await expect(page.getByRole("alert")).toContainText("No credits charged")
  await page.reload(); await open(page)
  await page.getByRole("button", { name: "Previous proposal", exact: true }).click()
  await expect(page.getByRole("heading", { name: "Community event proposal", exact: true })).toBeVisible()
  expect(await page.getByRole("region", { name: "Plan with AI", exact: true }).evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  await page.screenshot({ path: "/tmp/workspace-ai-plan-review-dark.png" })
  await page.getByRole("button", { name: "Discard proposal", exact: true }).click()
  await expect(page.getByRole("region", { name: "Proposed plan" })).toHaveCount(0)
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem("objective-fixture") || '{"planning":{"plans":[]}}').planning.plans.length)).toBe(0)
})


test("stops generation without applying a plan", async ({ page }) => {
  await generate(page, "slow fictional request")
  await page.getByRole("button", { name: "Stop request", exact: true }).click()
  await expect(page.getByRole("alert")).toContainText("No credits charged", { timeout: 5000 })
  expect(await page.evaluate(() => (Object.values(JSON.parse(localStorage.getItem("objective-ai-runs")!)) as { status: string; credits: number }[]).every(run => run.status === "canceled" && run.credits === 0))).toBe(true)
})

test("document context is deliberate, retained through recovery and removable after discard", async ({ page }) => {
  const context = page.getByRole("combobox", { name: "Plan document context" })
  await expect(context).toHaveText("No document")
  await context.click()
  await page.getByRole("option", { name: "Mission", exact: true }).click()
  await generate(page)
  await expect(context).toBeDisabled()
  await expect(page.getByRole("heading", { name: "Community event proposal", exact: true })).toBeVisible()
  expect(await page.evaluate(() => Object.values(JSON.parse(localStorage.getItem("objective-ai-runs") || "{}")))).toEqual([expect.objectContaining({ document: expect.objectContaining({ sectionId: "mission" }) })])
  await page.reload(); await open(page)
  await expect(context).toHaveText("Mission")
  await expect(context).toBeDisabled()
  await page.getByRole("button", { name: "Discard proposal", exact: true }).click()
  await expect(context).toBeEnabled()
  await context.click(); await page.getByRole("option", { name: "No document", exact: true }).click()
  await expect(context).toHaveText("No document")
})
