  await page.getByRole("button", { name: "Create invitation" }).click()
  await expect(page.getByRole("list", { name: "Page invitations" })).toContainText("person6@example.org")
  const { pageId, invitationId } = await page.evaluate(() => ({ pageId: JSON.parse(localStorage.getItem("sharing-canvas-fixture")!).pages[0].id, invitationId: JSON.parse(localStorage.getItem("sharing-guests-fixture")!).invites[0].id }))
