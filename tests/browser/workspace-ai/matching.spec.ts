import {test,expect} from '@playwright/test'
test('search, review, dismiss, undo and saved state survive reopening',async({page})=>{
 await page.goto('/?matching')
 await page.getByRole('button',{name:'Opportunities for Workshop'}).click()
 await page.getByRole('textbox',{name:'Public opportunity keywords'}).fill('community')
 await page.getByRole('button',{name:'Find',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Fictional opportunity — browser test'})).toBeVisible()
 await page.getByText('Why this match',{exact:true}).click()
 await expect(page.getByText(/This is not a per-award amount/)).toBeVisible()
 await page.getByRole('button',{name:'Dismiss match Fictional opportunity — browser test'}).click()
 await expect(page.getByRole('heading')).toHaveCount(0)
 await page.getByRole('button',{name:'Undo',exact:true}).click()
 await page.getByRole('button',{name:'Save match Fictional opportunity — browser test',exact:true}).click()
 await expect(page.getByRole('button',{name:'Saved match Fictional opportunity — browser test'})).toBeDisabled()
 await page.reload()
 await page.getByRole('button',{name:'Opportunities for Workshop'}).click()
 await expect(page.getByRole('button',{name:'Saved match Fictional opportunity — browser test'})).toBeDisabled()
 await page.getByRole('button',{name:'Switch resource'}).click()
 await page.getByRole('button',{name:'Opportunities for Second resource'}).click()
 await expect(page.getByRole('heading')).toHaveCount(0)
})
