import {test,expect} from '@playwright/test'
test('search, review, dismiss, undo and saved state survive reopening',async({page})=>{
 await page.goto('/?matching')
 await page.getByRole('button',{name:'Opportunities for Workshop'}).click()
 await page.getByRole('textbox',{name:'Public opportunity keywords'}).fill('community')
 await page.getByRole('button',{name:'Find',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Fictional opportunity — browser test'})).toBeVisible()
 await page.getByText('Why this match',{exact:true}).click()
 await expect(page.getByText(/This is not a per-award amount/)).toBeVisible()
 await page.getByRole('button',{name:'Dismiss match Fictional opportunity — browser test'}).click()
 await expect(page.getByRole('heading')).toHaveCount(0)
 await page.getByRole('button',{name:'Undo',exact:true}).click()
 await page.getByRole('button',{name:'Save match Fictional opportunity — browser test',exact:true}).click()
 await expect(page.getByRole('button',{name:'Saved match Fictional opportunity — browser test'})).toBeDisabled()
 await page.reload()
 await page.getByRole('button',{name:'Opportunities for Workshop'}).click()
 await expect(page.getByRole('button',{name:'Saved match Fictional opportunity — browser test'})).toBeDisabled()
 await page.getByRole('button',{name:'Switch resource'}).click()
 await page.getByRole('button',{name:'Opportunities for Second resource'}).click()
 await expect(page.getByRole('heading')).toHaveCount(0)
})
test('source failures leave a usable search and narrow view has no horizontal overflow',async({page})=>{
 await page.setViewportSize({width:390,height:844});await page.goto('/?matching')
 await page.getByRole('button',{name:'Opportunities for Workshop'}).click()
 await page.getByRole('textbox',{name:'Public opportunity keywords'}).fill('unavailable')
 await page.getByRole('button',{name:'Find',exact:true}).click()
 await expect(page.getByRole('alert')).toContainText('temporarily unavailable')
 await expect(page.getByRole('button',{name:'Find',exact:true})).toBeEnabled()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
})
test('inline funding review persists private inputs through search and reload',async({page})=>{
 await page.setViewportSize({width:390,height:844});await page.goto('/?matching')
 await page.getByRole('button',{name:'Opportunities for Workshop'}).click()
 await page.getByRole('textbox',{name:'Public opportunity keywords'}).fill('community')
 await page.getByRole('button',{name:'Find',exact:true}).click()
 await page.getByRole('button',{name:'Review funding & eligibility'}).click()
 await page.getByRole('textbox',{name:'Request',exact:true}).fill('7500')
 await page.getByRole('textbox',{name:'Eligible unfunded cost',exact:true}).fill('25000')
 await page.getByRole('combobox',{name:'Full requirements',exact:true}).click()
 await page.getByRole('option',{name:'Not met',exact:true}).click()
 await page.getByRole('button',{name:'Save review',exact:true}).click()
 await expect(page.getByText('Requirements not met',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Find',exact:true}).click()
 await page.reload();await page.getByRole('button',{name:'Opportunities for Workshop'}).click()
 await page.getByRole('button',{name:'Edit funding review',exact:true}).click()
 await expect(page.getByRole('textbox',{name:'Request',exact:true})).toHaveValue('7500.00')
 await expect(page.getByRole('textbox',{name:'Eligible unfunded cost',exact:true})).toHaveValue('25000.00')
 await expect(page.getByRole('combobox',{name:'Full requirements',exact:true})).toHaveText('Not met')
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
})
test('failed reads and source amendments preserve draft review for explicit reconsideration',async({page})=>{
 await page.goto('/?matching');await page.getByRole('button',{name:'Opportunities for Workshop'}).click()
 await page.getByRole('textbox',{name:'Public opportunity keywords'}).fill('community');await page.getByRole('button',{name:'Find',exact:true}).click()
 await page.getByRole('button',{name:'Review funding & eligibility'}).click()
 await page.getByRole('textbox',{name:'Request',exact:true}).fill('1234')
 await page.evaluate(()=>localStorage.setItem('matching-review-control','failure'))
 await page.getByRole('button',{name:'Save review',exact:true}).click()
 await expect(page.getByRole('alert')).toContainText('temporarily unavailable')
 await expect(page.getByRole('textbox',{name:'Request',exact:true})).toHaveValue('1234')
 await page.evaluate(()=>localStorage.setItem('matching-review-control','amendment'))
 await page.getByRole('button',{name:'Save review',exact:true}).click()
 await expect(page.getByRole('alert')).toContainText('official notice changed')
 await page.getByText('Published requirements',{exact:true}).click()
 await expect(page.getByText('Amended fictional requirements: local delivery is required.')).toBeVisible()
 await expect(page.getByRole('textbox',{name:'Request',exact:true})).toHaveValue('1234')
 await page.getByRole('button',{name:'Save review',exact:true}).click()
 await expect(page.getByRole('button',{name:'Edit funding review',exact:true})).toBeVisible()
})
