test('failed reads and source amendments preserve draft review for explicit reconsideration',async({page})=>{
 await page.goto('/?matching');await page.getByRole('button',{name:'Opportunities for Workshop'}).click()
 await page.getByRole('textbox',{name:'Public opportunity keywords'}).fill('community');await page.getByRole('button',{name:'Find',exact:true}).click()
 await page.getByRole('button',{name:'Review funding & eligibility'}).click()
 await page.getByRole('textbox',{name:'Request',exact:true}).fill('1234')
 await page.evaluate(()=>localStorage.setItem('matching-review-control','failure'))
 await page.getByRole('button',{name:'Save review',exact:true}).click()
 await expect(page.getByRole('alert')).toContainText('temporarily unavailable')
 await expect(page.getByRole('textbox',{name:'Request',exact:true})).toHaveValue('1234')
 await page.evaluate(()=>localStorage.setItem('matching-review-control','amendment'))
 await page.getByRole('button',{name:'Save review',exact:true}).click()
 await expect(page.getByRole('alert')).toContainText('official notice changed')
 await page.getByText('Published requirements',{exact:true}).click()
 await expect(page.getByText('Amended fictional requirements: local delivery is required.')).toBeVisible()
 await expect(page.getByRole('textbox',{name:'Request',exact:true})).toHaveValue('1234')
 await page.getByRole('button',{name:'Save review',exact:true}).click()
 await expect(page.getByRole('button',{name:'Edit funding review',exact:true})).toBeVisible()
})

test('application preparation requires Save and reopens one preserved document',async({page})=>{
 await page.addInitScript(()=>window.addEventListener('coach-house:workspace-roadmap-drawer-request',event=>{event.preventDefault();localStorage.setItem('application-open-count',String(Number(localStorage.getItem('application-open-count')??0)+1))}))
 await page.goto('/?matching');await page.getByRole('button',{name:'Opportunities for Workshop'}).click()
 await page.getByRole('textbox',{name:'Public opportunity keywords'}).fill('community');await page.getByRole('button',{name:'Find',exact:true}).click()
 await expect(page.getByRole('button',{name:'Application draft',exact:true})).toHaveCount(0)
 await page.getByRole('button',{name:'Save match Fictional opportunity — browser test',exact:true}).click()
 await page.getByRole('button',{name:'Application draft',exact:true}).click()
 await expect(page.getByRole('status')).toContainText('Nothing has been submitted')
 const initial=await page.evaluate(()=>Object.keys(localStorage).filter(key=>key.startsWith('matching-application:')).map(key=>JSON.parse(localStorage.getItem(key)!)))
 expect(initial).toHaveLength(1);expect(initial[0].content).toContain('Preparation draft')
 await page.evaluate(()=>{const key=Object.keys(localStorage).find(key=>key.startsWith('matching-application:'))!;const doc=JSON.parse(localStorage.getItem(key)!);doc.content='<p>Manual application edit</p>';localStorage.setItem(key,JSON.stringify(doc))})
 await page.goto('/?matching');await page.getByRole('button',{name:'Opportunities for Workshop'}).click();await page.getByRole('button',{name:'Application draft',exact:true}).click()
 const saved=await page.evaluate(()=>Object.keys(localStorage).filter(key=>key.startsWith('matching-application:')).map(key=>JSON.parse(localStorage.getItem(key)!)))
 expect(saved).toHaveLength(1);expect(saved[0].content).toBe('<p>Manual application edit</p>')
 expect(await page.evaluate(()=>localStorage.getItem('application-open-count'))).toBe('2')
 await expect(page.getByRole('button',{name:'Saved match Fictional opportunity — browser test'})).toBeDisabled()
})


