import { test,expect } from "@playwright/test"
test.beforeEach(async({page})=>{await page.route("**/*",route=>new URL(route.request().url()).hostname==="127.0.0.1"?route.continue():route.abort())})
test("requires explicit consent, resets it when terms change, and keeps configuration across reload",async({page})=>{
  await page.goto("/?credits&refill")
  const refill=page.getByRole("region",{name:"Auto-refill",exact:true})
  await expect(refill).toContainText("Off")
  await refill.getByRole("button",{name:"Set up auto-refill",exact:true}).click()
  const submit=refill.getByRole("button",{name:"Set up saved card",exact:true}),consent=refill.getByRole("checkbox")
  await expect(submit).toBeDisabled()
  await consent.check();await expect(submit).toBeEnabled()
  await refill.getByRole("spinbutton",{name:"Refill threshold"}).fill("50")
  await expect(consent).not.toBeChecked();await expect(submit).toBeDisabled()
  await consent.check()
  const popup=page.waitForEvent("popup");await submit.click();await (await popup).close()
  await expect(refill).toContainText("Awaiting card setup")
  await page.reload();await expect(refill).toContainText("Awaiting card setup")
  await refill.getByRole("button",{name:"Check status",exact:true}).click()
  await expect(refill).toContainText("visa 4242")
  await expect(refill).toContainText("$0.00 of $30.00 this month")
  await refill.getByRole("button",{name:"Disable auto-refill",exact:true}).click()
  await expect(refill).toContainText("Off")
  expect(await page.evaluate(()=>JSON.parse(localStorage.getItem("refill-calls")!).length)).toBe(1)
})
test("keeps uncertain setup retry stable and fits a narrow screen",async({page})=>{
  await page.setViewportSize({width:390,height:844});await page.goto("/?credits&refill&refill-failure")
  await page.evaluate(()=>document.documentElement.classList.add("dark"))
  const refill=page.getByRole("region",{name:"Auto-refill",exact:true})
  await refill.getByRole("button",{name:"Set up auto-refill",exact:true}).click();await refill.getByRole("checkbox").check()
  await refill.getByRole("button",{name:"Set up saved card",exact:true}).click()
  await expect(refill.getByRole("alert")).toContainText("confirmation pending")
  const popup=page.waitForEvent("popup");await refill.getByRole("button",{name:"Set up saved card",exact:true}).click();await(await popup).close()
  await expect(refill).toContainText("Awaiting card setup")
  const calls=await page.evaluate(()=>JSON.parse(localStorage.getItem("refill-calls")!));expect(calls).toHaveLength(2);expect(calls[0]).toEqual(calls[1])
  expect(await page.locator("main").evaluate(element=>element.scrollWidth<=element.clientWidth)).toBe(true)
  await page.screenshot({path:"/tmp/workspace-credit-refill-dark.png"})
})
test("does not show refill configuration to staff",async({page})=>{
  await page.goto("/?credits&refill&staff");await expect(page.getByText("100 credits available")).toBeVisible()
  await expect(page.getByRole("region",{name:"Auto-refill",exact:true})).toHaveCount(0)
})
