test("profile failures, timeouts and wrong response scopes discard metadata without stale resurrection", async ({ page }) => {
  await ready(page); await page.clock.install()
  const pending: Route[] = []
  await page.route(profilePath, route => { pending.push(route) })
  await focus(page); await expect.poll(() => pending.length).toBe(1)
  await page.clock.fastForward(15001)
  await expect(policyButton(page)).toHaveCount(0)
  await pending[0].fulfill({ json: data }).catch(() => {})
  await expect(policyButton(page)).toHaveCount(0)
  await page.getByRole("button", { name: "Retry", exact: true }).click()
  await expect.poll(() => pending.length).toBe(2)
  await pending[1].fulfill({ json: { ...data, userId: organizationId } })
  await expect(page.getByRole("status").filter({ hasText: "Documents unavailable" })).toBeVisible()
  await expect(policyButton(page)).toHaveCount(0)
  await page.getByRole("button", { name: "Retry", exact: true }).click()
  await expect.poll(() => pending.length).toBe(3)
  await pending[2].fulfill({ json: { ...data, policyEntries: [{}] } })
  await expect(page.getByRole("status").filter({ hasText: "Documents unavailable" })).toBeVisible()
  await page.getByRole("button", { name: "Retry", exact: true }).click()
  await expect.poll(() => pending.length).toBe(4)
  await pending[3].fulfill({ json: data })
  await expect(policyButton(page)).toBeVisible()
})
