import { expect, test, type Page, type Route } from "@playwright/test"
const userId = "00000000-0000-4000-8000-000000000001", organizationId = "00000000-0000-4000-8000-000000000002"
const profilePath = "**/api/account/organization-document-library?**"
const policy = { id: "policy-1", title: "Private policy", summary: "Private policy summary", status: "in_progress", categories: ["Board"], programId: null, personIds: [], document: null, updatedAt: "2026-11-11T00:00:00Z" }
const data = { userId, organizationId, canEdit: true, publicSlug: null,
  documents: { w9: { name: "Private W9.pdf", path: "org/w9.pdf", mime: "application/pdf" } },
  policyEntries: [policy], policyProgramOptions: [], policyPeopleOptions: [],
  roadmapSections: [{ id: "vision", title: "Private vision", subtitle: "Private vision subtitle", slug: "vision", status: "in_progress", content: "<p>Private core content</p>", hasContent: true, lastUpdated: null, isPublic: false }],
}
const focus = (page: Page) => page.evaluate(() => window.dispatchEvent(new Event("focus")))
const invalidate = (page: Page) => page.evaluate(orgId => window.dispatchEvent(new CustomEvent("coach-house:workspace-access-changed", { detail: { orgId } })), organizationId)
const policyButton = (page: Page) => page.getByRole("button", { name: "Open Private policy", exact: true })
async function ready(page: Page) {
  await page.route("**/api/account/workspace-notes?**", route => route.fulfill({ json: { notes: [] } }))
  await page.route("**/api/account/organization-document-files?**", route => route.fulfill({ json: { hasStorageAccess: true, files: [], quota: { usedBytes: 0, limitBytes: 1000 } } }))
  await page.route("**/api/integrations/google-drive/connection?**", route => route.fulfill({ json: { ok: true, connection: { connected: false } } }))
  await page.route("**/api/integrations/google-drive/documents?**", route => route.fulfill({ json: { ok: true, documents: [] } }))
  await page.route("**/api/account/org-documents?**", route => route.fulfill({ status: 404, json: {} }))
  await page.route(profilePath, route => route.fulfill({ json: data }))
  await page.goto("/profile-library.html")
  await expect(policyButton(page)).toBeVisible()
  await expect(page.getByRole("button", { name: "Open Private vision", exact: true })).toBeVisible()
}
test("profile library preserves drafts across checks and withholds rows and portals on denial", async ({ page }) => {
  await ready(page)
  await policyButton(page).click()
  await page.getByLabel("Summary", { exact: true }).fill("Unsaved policy work")
  await expect(page.locator('[data-fixture-dirty="dirty"]')).toBeVisible()
  const pending: Route[] = []
  await page.route(profilePath, route => { pending.push(route) })
  await focus(page); await focus(page)
  await expect.poll(() => pending.length).toBe(1)
  const params = new URL(pending[0].request().url()).searchParams
  expect(params.get("expectedUserId")).toBe(userId); expect(params.get("organizationId")).toBe(organizationId)
  await expect(page.getByLabel("Summary", { exact: true })).toHaveValue("Unsaved policy work")
  await pending[0].fulfill({ json: { ...data, policyEntries: [{ ...policy, summary: "Collaborator update" }] } })
  await expect(page.getByLabel("Summary", { exact: true })).toHaveValue("Unsaved policy work")
  await invalidate(page)
  await expect(page.getByRole("dialog")).toHaveCount(0)
  await expect(policyButton(page)).toHaveCount(0)
  await expect(page.getByText("Private core content", { exact: true })).toHaveCount(0)
  await expect.poll(() => pending.length).toBe(2)
  await pending[1].fulfill({ status: 403, json: {} })
  await expect(page.getByRole("status").filter({ hasText: "Documents unavailable" })).toBeVisible()
  await expect(page.locator('[data-fixture-dirty="dirty"]')).toBeVisible()
  await page.getByRole("button", { name: "Retry", exact: true }).click()
  await expect.poll(() => pending.length).toBe(3)
  await pending[2].fulfill({ json: data })
  await expect(page.getByLabel("Summary", { exact: true })).toHaveValue("Unsaved policy work")
})

test("hidden profile windows suspend reads and preserve the hidden policy draft", async ({ page }) => {
  await ready(page); await policyButton(page).click()
  await page.getByLabel("Summary", { exact: true }).fill("Draft before hiding")
  const pending: Route[] = []
  await page.route(profilePath, route => { pending.push(route) })
  const active = (value: boolean) => page.evaluate(value => window.dispatchEvent(new CustomEvent("fixture-window-active", { detail: value })), value)
  await active(false)
  await expect(page.getByRole("dialog")).toHaveCount(0)
  await expect(policyButton(page)).toHaveCount(0)
  await focus(page); await invalidate(page)
  expect(pending).toHaveLength(0)
  await active(true)
  await expect.poll(() => pending.length).toBe(1)
  await pending[0].fulfill({ json: data })
  await expect(page.getByLabel("Summary", { exact: true })).toHaveValue("Draft before hiding")
  await page.evaluate(() => window.dispatchEvent(new Event("pagehide")))
  await expect(page.getByRole("dialog")).toHaveCount(0)
  await page.evaluate(() => window.dispatchEvent(new Event("pageshow")))
  await expect.poll(() => pending.length).toBe(2)
  await pending[1].fulfill({ json: { ...data, policyEntries: [] } })
  await expect(page.getByRole("dialog")).toHaveCount(0)
  await expect(policyButton(page)).toHaveCount(0)
  await expect(page.locator('[data-fixture-dirty="dirty"]')).toBeVisible()
})
