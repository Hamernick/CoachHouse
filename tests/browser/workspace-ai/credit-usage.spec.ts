import { test, expect } from "@playwright/test"
test.beforeEach(async ({ page }) => {
  await page.route("**/*", route => new URL(route.request().url()).hostname === "127.0.0.1" ? route.continue() : route.abort())
})
test("history paginates and filters without exposing private source names", async ({ page }) => {
  await page.goto("/?credits")
  const records = page.getByRole("list", { name: "AI usage records" }).getByRole("listitem")
  await expect(records).toHaveCount(20)
  await page.getByRole("button", { name: "Show more", exact: true }).click()
  await expect(records).toHaveCount(25)
  await expect(page.getByRole("button", { name: "Show more", exact: true })).toHaveCount(0)
  await page.getByRole("combobox", { name: "Usage member" }).click()
  await page.getByRole("option", { name: "Fictional Teammate" }).click()
  await expect(records).toHaveCount(12)
  await expect(records.first()).toContainText("Plan")
  await expect(page.getByRole("list", { name: "AI usage records" })).not.toContainText("Document")
  await page.getByRole("combobox", { name: "Usage task" }).click()
  await page.getByRole("option", { name: "Documents", exact: true }).click()
  await expect(page.getByText("No usage yet.", { exact: true })).toBeVisible()
})
test("member usage remains compact in dark mode and offers no team filter", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto("/?credits&staff")
  await page.evaluate(() => document.documentElement.classList.add("dark"))
  await expect(page.getByRole("list", { name: "AI usage records" }).getByRole("listitem")).toHaveCount(13)
  await expect(page.getByRole("combobox", { name: "Usage member" })).toHaveCount(0)
  expect(await page.locator("main").evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  await page.screenshot({ path: "/tmp/workspace-credit-usage-dark.png" })
})
test("Usage opens from the account action without selecting a document or starting AI", async ({ page }) => {
  await page.goto("/?usage-navigation")
  await page.getByRole("button", { name: "Usage", exact: true }).click()
  await expect(page.getByRole("region", { name: "Usage", exact: true })).toBeVisible()
  await expect(page.getByText("100 credits available")).toBeVisible()
  await expect(page.getByRole("list", { name: "AI usage records" }).getByRole("listitem")).toHaveCount(20)
  await page.getByRole("button", { name: "Close", exact: true }).click()
  await expect(page.getByRole("region", { name: "Usage", exact: true })).toHaveCount(0)
})

test("failed usage reads recover without losing the selected filter", async ({ page }) => {
  await page.goto("/?credits&usage-error")
  await expect(page.getByRole("alert")).toContainText("Unable to load AI usage")
  await page.evaluate(() => sessionStorage.setItem("usage-available", "true"))
  await page.getByRole("button", { name: "Retry", exact: true }).click()
  await expect(page.getByRole("list", { name: "AI usage records" }).getByRole("listitem")).toHaveCount(20)
  await page.evaluate(() => sessionStorage.removeItem("usage-available"))
  await page.getByRole("combobox", { name: "Usage task" }).click()
  await page.getByRole("option", { name: "Plans", exact: true }).click()
  await expect(page.getByRole("alert")).toContainText("Unable to load AI usage")
  await expect(page.getByRole("combobox", { name: "Usage task" })).toContainText("Plans")
  await page.evaluate(() => sessionStorage.setItem("usage-available", "true"))
  await page.getByRole("button", { name: "Retry", exact: true }).click()
  await expect(page.getByRole("list", { name: "AI usage records" }).getByRole("listitem")).toHaveCount(12)
})


test("usage sits beside the input, appears on hover and stays usable through its popover", async ({ page }) => {
  await page.goto("/?usage-dock")
  const input = page.getByRole("textbox", { name: "Search Particles or enter a command" })
  const usage = page.getByRole("button", { name: /^AI usage:/ })
  await page.mouse.move(20, 20)
  await expect(usage.locator("..")).toHaveCSS("opacity", "0")
  await input.hover()
  await expect(usage.locator("..")).toHaveCSS("opacity", "1")
  const bar = (await input.locator("xpath=ancestor::form").boundingBox())!
  const icon = (await usage.boundingBox())!
  expect(icon.x + icon.width).toBeLessThan(bar.x)
  expect(icon.y + icon.height / 2).toBeCloseTo(bar.y + bar.height / 2, 0)
  await usage.hover()
  await expect(usage.locator("..")).toHaveCSS("opacity", "1")
  await usage.click()
  await expect(page.getByRole("dialog", { name: "AI usage", exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Manage usage", exact: true }).click()
  await expect(page.getByTestId("usage-manage-request")).toHaveText("1")
  await page.mouse.move(20, 20)
  await usage.focus()
  await expect(usage).toBeFocused()
  await expect(usage.locator("..")).toHaveCSS("opacity", "1")
})
