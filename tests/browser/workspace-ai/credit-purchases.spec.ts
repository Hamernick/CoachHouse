import { test, expect } from "@playwright/test"
test.beforeEach(async ({ page }) => {
  await page.route("**/*", route => new URL(route.request().url()).hostname === "127.0.0.1" ? route.continue() : route.abort())
})
test("opens checkout separately, retains workspace, reconciles verified credits and permits another purchase", async ({ page }) => {
  await page.goto("/?credits")
  await expect(page.getByRole("combobox", { name: "Credit pack" })).toContainText("1,000 credits")
  const popup = page.waitForEvent("popup")
  await page.getByRole("button", { name: "Buy credits", exact: true }).click()
  const checkout = await popup
  await expect(checkout).toHaveURL(/fixture-checkout/)
  await expect(page).toHaveURL(/\?credits$/)
  await page.evaluate(() => window.dispatchEvent(new Event("focus")))
  await expect(page.getByText("Awaiting payment confirmation")).toBeVisible()
  await expect(page.getByText("100 credits available")).toBeVisible()
  await checkout.close()
  await page.evaluate(() => { localStorage.setItem("credit-paid", "true"); window.dispatchEvent(new Event("focus")) })
  await expect(page.getByText("1,100 credits available")).toBeVisible()
  await expect(page.getByText("Credited", { exact: true })).toBeVisible()
  const secondPopup = page.waitForEvent("popup")
  await page.getByRole("button", { name: "Buy credits", exact: true }).click()
  await (await secondPopup).close()
  const calls = await page.evaluate(() => JSON.parse(localStorage.getItem("credit-calls")!))
  expect(calls).toHaveLength(2)
  expect(calls[0].id).not.toBe(calls[1].id)
})
test("uncertain checkout retries the same purchase and stays usable in narrow dark mode", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto("/?credits&failure")
  await page.evaluate(() => document.documentElement.classList.add("dark"))
  await page.getByRole("button", { name: "Buy credits", exact: true }).click()
  await expect(page.getByRole("alert")).toContainText("Retry this purchase")
  const popup = page.waitForEvent("popup")
  await page.getByRole("button", { name: "Buy credits", exact: true }).click()
  await (await popup).close()
  const calls = await page.evaluate(() => JSON.parse(localStorage.getItem("credit-calls")!))
  expect(calls).toHaveLength(2)
  expect(calls[0]).toEqual(calls[1])
  expect(await page.locator("main").evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  await page.screenshot({ path: "/tmp/workspace-credit-purchases-dark.png" })
})
test("members see usage without purchase controls", async ({ page }) => {
  await page.goto("/?credits&staff")
  await expect(page.getByText("100 credits available")).toBeVisible()
  await expect(page.getByRole("button", { name: "Buy credits", exact: true })).toHaveCount(0)
})
