import { test, expect } from "@playwright/test"

test.beforeEach(async ({ page }) => {
  await page.route("**/*", route => new URL(route.request().url()).hostname === "127.0.0.1" ? route.continue() : route.abort())
  await page.goto("/?objectives")
  await page.getByRole("button", { name: "Objectives", exact: true }).click()
})
test("create, edit, complete a step and reopen saved objective", async ({ page }) => {
  await page.getByRole("button", { name: "Launch a volunteer program", exact: true }).click()
  await page.getByRole("checkbox", { name: "Recruit the first team" }).check()
  await expect(page.getByText("2 / 3 steps")).toBeVisible()
  await page.getByLabel("New objective", { exact: true }).fill("Plan our community event")
  await page.getByRole("button", { name: "Add objective", exact: true }).click()
  await expect(page.getByRole("button", { name: "Plan our community event", exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Edit Plan our community event", exact: true }).click()
  await page.getByLabel("Objective", { exact: true }).fill("Plan our spring event")
  await page.getByLabel("Details", { exact: true }).fill("Invite neighbors and volunteers.")
  // Collapsing the island retains the user's unsaved edit.
  await page.getByRole("button", { name: "Objectives", exact: true }).click()
  await page.getByRole("button", { name: "Objectives", exact: true }).click()
  await expect(page.getByLabel("Objective", { exact: true })).toHaveValue("Plan our spring event")
  await expect(page.getByRole("button", { name: "Save", exact: true })).toBeEnabled()
  await page.getByRole("button", { name: "Save", exact: true }).click()
  await expect(page.getByRole("button", { name: "Plan our spring event", exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole("button", { name: "Objectives", exact: true }).click()
  await expect(page.getByRole("button", { name: "Plan our spring event", exact: true })).toBeVisible()
  await expect(page.getByText("2 / 3 steps")).toBeVisible()
})
test("stale edits retain input and switching organizations removes private state", async ({ page }) => {
  await page.getByRole("button", { name: "Edit Launch a volunteer program", exact: true }).click()
  await page.getByLabel("Objective", { exact: true }).fill("My unsaved objective")
  // Use the fixture action directly: it sits below the expanded overlay.
  await page.getByRole("button", { name: "Simulate collaborator edit" }).evaluate((button: HTMLButtonElement) => button.click())
  await page.getByRole("button", { name: "Save", exact: true }).click()
  await expect(page.getByRole("alert")).toContainText("changed")
  await expect(page.getByLabel("Objective", { exact: true })).toHaveValue("My unsaved objective")
  await page.getByRole("button", { name: "Refresh", exact: true }).click()
  await expect(page.getByRole("button", { name: "Save", exact: true })).toBeEnabled()
  await page.getByRole("button", { name: "Save", exact: true }).click()
  await expect(page.getByRole("alert")).toContainText("changed")
  await expect(page.getByLabel("Objective", { exact: true })).toHaveValue("My unsaved objective")
  await page.getByRole("button", { name: "Switch fixture organization" }).evaluate((button: HTMLButtonElement) => button.click())
  await page.getByRole("button", { name: "Objectives", exact: true }).click()
  await expect(page.getByText("No objectives yet.")).toBeVisible()
  await expect(page.locator('input[value="My unsaved objective"]')).toHaveCount(0)
})
test("narrow dark and reduced-motion layout fits the viewport", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ reducedMotion: "reduce", colorScheme: "dark" })
  await page.evaluate(() => document.documentElement.classList.add("dark"))
  await page.getByRole("button", { name: "Launch a volunteer program", exact: true }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: "/tmp/workspace-objectives-island-dark.png" })
})
