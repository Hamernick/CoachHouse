import { afterEach, beforeEach, describe, expect, it, vi } from "vitest"
import { GuestDraftController } from "@/features/fiscal-sponsorship/lib/guest-draft-controller"

const expiry = "2026-10-17T00:00:00Z"
const reference = "20000000-0000-4000-8000-000000000001"
const draftResponse = (draft = {}, version = 0) => Response.json({ state: "draft", draft, version, expiresAt: expiry })
const clients: GuestDraftController[] = []
function setup(enabled = true) {
  const transport = vi.fn<typeof fetch>().mockImplementation(async (url, init) => {
    if (String(url).endsWith("session")) return Response.json({ ok: true })
    const body = JSON.parse(String(init?.body))
    return body.operation === "read" ? draftResponse() : draftResponse(body.draft, body.version + 1)
  })
  const client = new GuestDraftController(enabled, transport)
  clients.push(client)
  const saves = () => transport.mock.calls.map(([, init]) => JSON.parse(String(init?.body))).filter((body) => body.operation === "save")
  return { client, transport, saves }
}
beforeEach(() => vi.useFakeTimers())
afterEach(() => { clients.splice(0).forEach((client) => client.stop()); vi.useRealTimers() })

describe("guest draft autosave and recovery", () => {
  it("invokes browser fetch without binding it to the draft controller", async () => {
    const transport = vi.fn<typeof fetch>(async function (this: unknown, url, init) {
      if (this !== undefined && this !== globalThis) {
        throw new TypeError("Failed to execute fetch on Window: Illegal invocation")
      }
      if (String(url).endsWith("session")) return Response.json({ ok: true })
      const body = JSON.parse(String(init?.body))
      return body.operation === "read" ? draftResponse() : draftResponse(body.draft, body.version + 1)
    })
    const client = new GuestDraftController(true, transport)
    clients.push(client)
    await client.start()
    expect(client.getSnapshot()).toMatchObject({ phase: "ready", dirty: false })
    client.edit("projectName", "Ready to submit")
    expect(await client.flush()).toBe(true)
    expect(client.getSnapshot()).toMatchObject({ phase: "ready", saved: true, dirty: false })
    expect(transport).toHaveBeenCalledTimes(3)
    expect(transport.mock.contexts.every((context) => context !== client)).toBe(true)
  })

  it("flushes the latest answers after an in-flight save before submission", async () => {
    const { client, transport, saves } = setup()
    await client.start()
    let finish!: (response: Response) => void
    transport.mockImplementationOnce(() => new Promise((resolve) => { finish = resolve }))
    client.edit("projectName", "First")
    const saving = client.save()
    client.edit("projectName", "Final answer")
    const flushing = client.flush()
    finish(draftResponse(saves()[0].draft, 1))
    await saving
    expect(await flushing).toBe(true)
    expect(saves()[1]).toMatchObject({ version: 1, draft: { projectName: "Final answer" } })
    client.acceptSubmission(reference)
    await vi.advanceTimersByTimeAsync(2000)
    expect(saves()).toHaveLength(2)
    expect(client.getSnapshot()).toMatchObject({ phase: "submitted", reference, dirty: false })
  })
  it("does not flush through a failed save and retains answers after session expiry", async () => {
    const { client, transport } = setup()
    await client.start()
    client.edit("projectName", "Keep this")
    transport.mockRejectedValueOnce(new Error("offline"))
    expect(await client.flush()).toBe(false)
    client.expireSession()
    await client.retry()
    expect(client.getSnapshot()).toMatchObject({ phase: "ready", dirty: true, draft: { projectName: "Keep this" } })
  })
  it("keeps preview edits in memory without starting a session or sending answers", async () => {
    const { client, transport } = setup(false)
    await client.start()
    client.edit("projectName", "Local preview")
    await vi.advanceTimersByTimeAsync(2000)
    expect(client.getSnapshot()).toMatchObject({ phase: "preview", dirty: true, saved: false })
    expect(transport).not.toHaveBeenCalled()
  })
  it("restores the private draft before accepting edits", async () => {
    const { client, transport } = setup()
    transport.mockResolvedValueOnce(Response.json({ ok: true })).mockResolvedValueOnce(draftResponse({ projectName: "Recovered" }, 3))
    client.edit("projectName", "Must not race restore")
    await client.start()
    expect(client.getSnapshot()).toMatchObject({ phase: "ready", draft: { projectName: "Recovered" }, dirty: false, saved: true })
    expect(transport.mock.calls[1][1]).toMatchObject({ cache: "no-store", credentials: "same-origin" })
  })
  it("debounces edits and marks saved only after acknowledgement", async () => {
    const { client, saves } = setup()
    await client.start()
    client.edit("projectName", "G")
    await vi.advanceTimersByTimeAsync(500)
    client.edit("projectName", "Garden")
    await vi.advanceTimersByTimeAsync(999)
    expect(saves()).toHaveLength(0)
    expect(client.getSnapshot().dirty).toBe(true)
    await vi.advanceTimersByTimeAsync(1)
    expect(saves()).toHaveLength(1)
    expect(saves()[0]).toMatchObject({ version: 0, draft: { projectName: "Garden" } })
    expect(saves()[0].draft).not.toHaveProperty("projectId")
    expect(client.getSnapshot()).toMatchObject({ phase: "ready", dirty: false, saved: true })
  })
  it("serializes edits made while a save is in flight", async () => {
    const { client, transport, saves } = setup()
    await client.start()
    let finish!: (response: Response) => void
    transport.mockImplementationOnce(() => new Promise((resolve) => { finish = resolve }))
    client.edit("projectName", "First")
    const saving = client.save()
    expect(client.getSnapshot()).toMatchObject({ phase: "saving", dirty: true, saved: false })
    client.edit("projectName", "Second")
    finish(draftResponse(saves()[0].draft, 1))
    await saving
    expect(client.getSnapshot()).toMatchObject({ draft: { projectName: "Second" }, dirty: true })
    await vi.advanceTimersByTimeAsync(1000)
    expect(saves()[1]).toMatchObject({ version: 1, draft: { projectName: "Second" } })
    expect(client.getSnapshot().dirty).toBe(false)
  })
  it("keeps navigation protection when reverting an answer during an in-flight write", async () => {
    const { client, transport, saves } = setup()
    await client.start()
    let finish!: (response: Response) => void
    transport.mockImplementationOnce(() => new Promise((resolve) => { finish = resolve }))
    client.edit("projectName", "Temporary")
    const saving = client.save()
    client.edit("projectName", "")
    expect(client.getSnapshot().dirty).toBe(true)
    finish(draftResponse(saves()[0].draft, 1)); await saving
    expect(client.getSnapshot().dirty).toBe(true)
    await vi.advanceTimersByTimeAsync(1000)
    expect(saves()[1].draft.projectName).toBe("")
  })
  it("retries the identical uncertain write before sending newer edits", async () => {
    const { client, transport, saves } = setup()
    await client.start()
    client.edit("projectName", "First")
    transport.mockRejectedValueOnce(new Error("network"))
    await client.save()
    expect(client.getSnapshot()).toMatchObject({ phase: "error", dirty: true, saved: false })
    client.edit("projectName", "Second")
    await vi.advanceTimersByTimeAsync(10000)
    expect(saves()).toHaveLength(1)
    await client.retry()
    expect(saves()[1]).toEqual(saves()[0])
    await vi.advanceTimersByTimeAsync(1000)
    expect(saves()[2]).toMatchObject({ version: 1, draft: { projectName: "Second" } })
  })
  it("preserves local answers on conflict until explicit reload", async () => {
    const { client, transport, saves } = setup()
    await client.start()
    client.edit("projectName", "This tab")
    transport.mockResolvedValueOnce(Response.json({ state: "conflict" }, { status: 409 }))
    await client.save()
    expect(client.getSnapshot()).toMatchObject({ phase: "conflict", dirty: true, draft: { projectName: "This tab" } })
    await vi.advanceTimersByTimeAsync(5000)
    expect(saves()).toHaveLength(1)
    transport.mockResolvedValueOnce(Response.json({ ok: true })).mockResolvedValueOnce(draftResponse({ projectName: "Other tab" }, 2))
    await client.reloadSaved()
    expect(client.getSnapshot()).toMatchObject({ phase: "ready", dirty: false, draft: { projectName: "Other tab" } })
  })
  it("retains edits when an initial read fails and requires reconciliation if a different draft exists", async () => {
    const { client, transport } = setup()
    transport.mockRejectedValueOnce(new Error("offline"))
    await client.start()
    client.edit("projectName", "Typed offline")
    transport.mockResolvedValueOnce(Response.json({ ok: true })).mockResolvedValueOnce(draftResponse({ projectName: "Saved earlier" }, 2))
    await client.retry()
    expect(client.getSnapshot()).toMatchObject({ phase: "conflict", dirty: true, draft: { projectName: "Typed offline" } })
  })
  it("resumes after expiry without dropping unsaved answers", async () => {
    const { client, transport, saves } = setup()
    await client.start()
    client.edit("projectName", "Still here")
    transport.mockResolvedValueOnce(Response.json({ state: "expired" }, { status: 401 }))
    await client.save()
    expect(client.getSnapshot()).toMatchObject({ phase: "expired", dirty: true })
    await client.retry()
    expect(client.getSnapshot()).toMatchObject({ phase: "ready", draft: { projectName: "Still here" }, dirty: true })
    await vi.advanceTimersByTimeAsync(1000)
    expect(saves()[1]).toMatchObject({ version: 0, draft: { projectName: "Still here" } })
  })
  it("preserves overlong input rather than truncating or falsely reporting saved", async () => {
    const { client, saves } = setup()
    await client.start()
    client.edit("projectName", "x".repeat(201))
    await vi.advanceTimersByTimeAsync(1000)
    expect(client.getSnapshot()).toMatchObject({ phase: "invalid", dirty: true })
    expect(client.getSnapshot().draft.projectName).toHaveLength(201)
    expect(saves()).toHaveLength(0)
    client.edit("projectName", "Short enough")
    await vi.advanceTimersByTimeAsync(1000)
    expect(client.getSnapshot()).toMatchObject({ phase: "ready", dirty: false })
  })
  it("recognizes already submitted applications without resubmitting or exposing answers", async () => {
    const { client, transport } = setup()
    transport.mockResolvedValueOnce(Response.json({ ok: true })).mockResolvedValueOnce(Response.json({ state: "submitted", reference }))
    await client.start()
    expect(client.getSnapshot()).toMatchObject({ phase: "submitted", dirty: false, reference })
    client.edit("projectName", "Too late")
    expect(client.getSnapshot().draft.projectName).toBe("")
  })
  it("cancels scheduled work on unmount", async () => {
    const { client, saves } = setup()
    await client.start()
    client.edit("projectName", "Unsent")
    client.stop()
    await vi.advanceTimersByTimeAsync(5000)
    expect(saves()).toHaveLength(0)
  })
  it("ignores old responses after stop and safely retries pending writes on restart", async () => {
    const { client, transport, saves } = setup()
    await client.start()
    let finish!: (response: Response) => void
    transport.mockImplementationOnce(() => new Promise((resolve) => { finish = resolve }))
    client.edit("projectName", "Pending")
    const saving = client.save()
    client.stop()
    finish(draftResponse(saves()[0].draft, 1)); await saving
    expect(client.getSnapshot().dirty).toBe(true)
    await client.start()
    expect(saves()[1]).toEqual(saves()[0])
    expect(client.getSnapshot().dirty).toBe(false)
  })
})
