import { expect, test } from "@playwright/test"

const fixture = "/visual-regression/tasks?taskWeek=2026-10-19"
test.use({ extraHTTPHeaders: { "x-coach-house-visual-regression": "1" } })

// Sample persistence checks exercise the real page orchestration. Actual SQL
// persistence, permissions and races are covered by task-planning.assertions.sql.
for (const width of [1440, 390]) {
  test(`personal tasks conserve records and save across views (${width})`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto(fixture)
    await expect(page.getByRole("button", { name: "Board", exact: true })).toBeVisible()
    await page.getByRole("checkbox", { name: "Complete Confirm the community venue", exact: true }).click()
    await page.reload()
    await expect(page.getByRole("checkbox", { name: "Reopen Confirm the community venue", exact: true })).toBeChecked()
    await expect(page.getByRole("button", { name: "Edit Review fiscal application" })).toHaveCount(0)
    await page.getByRole("button", { name: "Board", exact: true }).click()
    await expect(page).toHaveURL(/taskView=board/)
    await expect(page.getByRole("region", { name: "Unscheduled", exact: true })).toContainText("Review fiscal application")
    await expect(page.getByRole("button", { name: "Show weekend (1)", exact: true })).toBeVisible()
    await expect(page.getByText("Outside this week (1)", { exact: true })).toBeVisible()
    await expect(page.getByRole("button", { name: "Schedule Review fiscal application" })).toHaveCount(0)
    await page.getByRole("button", { name: "Schedule Prepare volunteer welcome notes", exact: true }).click()
    await page.getByLabel("Start date", { exact: true }).fill("2026-10-22")
    await page.getByRole("button", { name: "Save date", exact: true }).click()
    await expect(page.getByRole("button", { name: "Save date", exact: true })).toBeHidden()
    await page.reload()
    await expect(page.getByRole("article", { name: "Prepare volunteer welcome notes", exact: true })).toContainText("Oct 22")
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await testInfo.attach(`tasks-board-${width}`, { body: await page.screenshot({ fullPage: true }), contentType: "image/png" })
    await page.getByRole("button", { name: "Show weekend (1)", exact: true }).click()
    await expect(page.getByRole("button", { name: "Hide weekend", exact: true })).toBeVisible()
    await page.getByRole("button", { name: "List", exact: true }).click()
    await page.getByRole("button", { name: "Edit Review the program budget", exact: true }).click()
    const dialog = page.getByRole("dialog", { name: "Edit task", exact: true })
    await dialog.locator("#task-create-title").fill("Reviewed program budget")
    await dialog.getByRole("button", { name: "Save changes", exact: true }).click()
    await expect(dialog).toBeHidden()
    await page.reload()
    await expect(page.getByRole("button", { name: "Edit Reviewed program budget", exact: true })).toBeVisible()
  })
}

test("empty filtered tasks retain usable view and create controls", async ({ page }) => {
  const filters = encodeURIComponent(JSON.stringify([{ key: "Tag", value: "No matching tag" }]))
  await page.goto(`${fixture}&taskFilters=${filters}`)
  await expect(page.getByText("No tasks match the current filters.")).toBeVisible()
  await expect(page.getByRole("button", { name: "New Task", exact: true })).toBeEnabled()
  await expect(page.getByRole("button", { name: "Board", exact: true })).toBeEnabled()
})

test("scheduling rejection retains the draft and stored date", async ({ page }) => {
  await page.goto(`${fixture}&taskView=board&rejectSchedule=1`)
  await page.getByRole("button", { name: "Schedule Confirm the community venue", exact: true }).click()
  await page.getByLabel("Start date", { exact: true }).fill("2026-10-21")
  await page.getByRole("button", { name: "Save date", exact: true }).click()
  await expect(page.getByText("Sample conflict: this task changed. Refresh and try again.")).toBeVisible()
  await expect(page.getByLabel("Start date", { exact: true })).toHaveValue("2026-10-21")
  await page.keyboard.press("Escape")
  await page.reload()
  await expect(page.getByRole("article", { name: "Confirm the community venue", exact: true })).toContainText("Oct 20")
})

test("board creation carries the chosen calendar day into the persisted task", async ({ page }) => {
  await page.goto(`${fixture}&taskView=board`)
  await page.getByRole("button", { name: /^Add task to (22.*Thu|Thu.*22)$/ }).click()
  const dialog = page.getByRole("dialog", { name: "Create task", exact: true })
  await expect(dialog.getByRole("button", { name: "Start: 22/10/2026", exact: true })).toBeVisible()
  await dialog.locator("#task-create-title").fill("New Thursday task")
  await dialog.getByRole("button", { name: "Create Task", exact: true }).click()
  await expect(dialog).toBeHidden()
  await page.reload()
  await expect(page.getByRole("article", { name: "New Thursday task", exact: true })).toContainText("Oct 22")
})

test("drag schedules across days and relative list ordering survives reload", async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto(`${fixture}&taskView=board`)
  const handle = page.getByRole("button", { name: "Drag Confirm the community venue to another day", exact: true })
  const monday = page.getByRole("region", { name: /19.*Mon|Mon.*19/ })
  await expect(handle).toBeEnabled()
  await page.evaluate(() => document.fonts.ready)
  const from = await handle.boundingBox()
  const to = await monday.boundingBox()
  expect(from).not.toBeNull()
  expect(to).not.toBeNull()
  await page.mouse.move(from!.x + from!.width / 2, from!.y + from!.height / 2)
  await page.mouse.down()
  await page.mouse.move(from!.x + from!.width / 2 - 12, from!.y + from!.height / 2, { steps: 3 })
  await expect(page.getByRole("article", { name: "Confirm the community venue", exact: true })).toHaveClass(/opacity-40/)
  await page.mouse.move(to!.x + 100, to!.y + 120, { steps: 12 })
  await expect(monday).toHaveClass(/ring-2/)
  await page.mouse.up()
  await expect(monday.getByRole("article", { name: "Confirm the community venue", exact: true })).toBeVisible()
  await page.reload()
  await expect(monday.getByRole("article", { name: "Confirm the community venue", exact: true })).toBeVisible()
  await page.getByRole("button", { name: "List", exact: true }).click()
  await page.getByRole("button", { name: "Move Confirm the community venue down", exact: true }).click()
  await page.reload()
  const list = page.getByRole("list", { name: "Community program tasks", exact: true }).filter({ hasText: "Confirm the community venue" })
  await expect(list.getByRole("listitem").first()).toContainText("Review the program budget")
  await page.goBack()
  await expect(page.getByRole("region", { name: "Weekly task board" })).toBeVisible()
})
