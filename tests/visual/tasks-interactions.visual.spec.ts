test("drag schedules across days and relative list ordering survives reload", async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto(`${fixture}&taskView=board`, { waitUntil: "domcontentloaded" })
  await waitForTasks(page)
  const handle = page.getByRole("button", { name: "Drag Confirm the community venue to another day", exact: true })
  const monday = page.getByRole("region", { name: /19.*Mon|Mon.*19/ })
  await expect(handle).toBeEnabled()
  await page.evaluate(() => document.fonts.ready)
  const from = await handle.boundingBox()
  const to = await monday.boundingBox()
  expect(from).not.toBeNull()
  expect(to).not.toBeNull()
  await page.mouse.move(from!.x + from!.width / 2, from!.y + from!.height / 2)
  await page.mouse.down()
  await page.mouse.move(from!.x + from!.width / 2 - 12, from!.y + from!.height / 2, { steps: 3 })
  const source = page.locator('article[aria-label="Confirm the community venue"]')
  await expect(source).toHaveAttribute("inert", "")
  await expect(source).toHaveCSS("user-select", "none")
  await source.locator("button").first().evaluate(button => button.focus())
  expect(await source.evaluate(card => card.contains(document.activeElement))).toBe(false)
  await page.mouse.move(to!.x + 100, to!.y + 120, { steps: 12 })
  await expect(monday).toHaveClass(/ring-2/)
  await page.mouse.up()
  await expect(monday.getByRole("article", { name: "Confirm the community venue", exact: true })).toBeVisible()
  await expect(source).not.toHaveAttribute("inert")
  await page.reload({ waitUntil: "domcontentloaded" })
  await waitForTasks(page)
  await expect(monday.getByRole("article", { name: "Confirm the community venue", exact: true })).toBeVisible()
  await page.getByRole("button", { name: "List", exact: true }).click()
  await page.getByRole("button", { name: "Move Confirm the community venue down", exact: true }).click()
  await page.reload({ waitUntil: "domcontentloaded" })
  await waitForTasks(page)
  const list = page.getByRole("list", { name: "Community program tasks", exact: true }).filter({ hasText: "Confirm the community venue" })
  await expect(list.getByRole("listitem").first()).toContainText("Review the program budget")
  await page.goBack()
  await expect(page.getByRole("region", { name: "Weekly task board" })).toBeVisible()
})


