import { expect, test, type Page } from "@playwright/test"

const fixture = "/visual-regression/tasks?taskWeek=2026-10-19"
test.use({ extraHTTPHeaders: { "x-coach-house-visual-regression": "1" } })

async function waitForTasks(page: Page) {
  // The fixture restores its tab-local records after hydration.
  await page.getByRole("button", { name: "Board", exact: true }).waitFor({ state: "visible", timeout: 30000 })
}

// Sample persistence checks exercise the real page orchestration. Actual SQL
// persistence, permissions and races are covered by task-planning.assertions.sql.
for (const width of [1440, 390]) {
  test(`personal tasks conserve records and save across views (${width})`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto(fixture, { waitUntil: "domcontentloaded" })
    await waitForTasks(page)
    await expect(page.getByRole("button", { name: "Board", exact: true })).toBeVisible()
    await page.getByRole("checkbox", { name: "Complete Confirm the community venue", exact: true }).click()
    await page.reload({ waitUntil: "domcontentloaded" })
    await waitForTasks(page)
    await expect(page.getByRole("checkbox", { name: "Reopen Confirm the community venue", exact: true })).toBeChecked()
    await expect(page.getByRole("button", { name: "Edit Review fiscal application" })).toHaveCount(0)
    await page.getByRole("button", { name: "Board", exact: true }).click()
    await expect(page).toHaveURL(/taskView=board/)
    await expect(page.getByRole("region", { name: "Unscheduled", exact: true })).toContainText("Review fiscal application")
    await expect(page.getByRole("button", { name: "Show weekend (1)", exact: true })).toBeVisible()
    await expect(page.getByText("Outside this week (1)", { exact: true })).toBeVisible()
    await expect(page.getByRole("button", { name: "Schedule Review fiscal application" })).toHaveCount(0)
    await page.getByRole("button", { name: "Schedule Prepare volunteer welcome notes", exact: true }).click()
    await page.getByLabel("Start date", { exact: true }).fill("2026-10-22")
    await page.getByRole("button", { name: "Save date", exact: true }).click()
    await expect(page.getByRole("button", { name: "Save date", exact: true })).toBeHidden()
    await page.reload({ waitUntil: "domcontentloaded" })
    await waitForTasks(page)
    await expect(page.getByRole("article", { name: "Prepare volunteer welcome notes", exact: true })).toContainText("Oct 22")
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await testInfo.attach(`tasks-board-${width}`, { body: await page.screenshot({ fullPage: true }), contentType: "image/png" })
    await page.getByRole("button", { name: "Show weekend (1)", exact: true }).click()
    await expect(page.getByRole("button", { name: "Hide weekend", exact: true })).toBeVisible()
    await page.getByRole("button", { name: "List", exact: true }).click()
    await page.getByRole("button", { name: "Edit Review the program budget", exact: true }).click()
    const dialog = page.getByRole("dialog", { name: "Edit task", exact: true })
    await dialog.locator("#task-create-title").fill("Reviewed program budget")
    await dialog.getByRole("button", { name: "Save changes", exact: true }).click()
    await expect(dialog).toBeHidden()
    await page.reload({ waitUntil: "domcontentloaded" })
    await waitForTasks(page)
    await expect(page.getByRole("button", { name: "Edit Reviewed program budget", exact: true })).toBeVisible()
  })
}

