test.describe("browser-local calendar hydration", () => {
  test.use({ timezoneId: "America/New_York" })
  for (const taskWeek of [null, "2026-02-30"]) {
    test(`direct board hydration recovers ${taskWeek === null ? "a missing" : "an invalid"} week`, async ({ page }) => {
      const errors: string[] = []
      page.on("pageerror", error => errors.push(error.message))
      await page.clock.setFixedTime(new Date("2026-10-22T12:00:00Z"))
      const params = new URLSearchParams({ taskView: "board", ssr: "1" })
      if (taskWeek !== null) params.set("taskWeek", taskWeek)
      const response = await page.goto(`/visual-regression/tasks?${params}`, { waitUntil: "domcontentloaded" })
      expect(await response!.text()).toContain("Loading task calendar")
      const board = page.getByRole("region", { name: "Weekly task board", exact: true })
      await expect(board).toBeVisible()
      await expect(board.getByRole("heading", { level: 2 })).toHaveText("Oct 19 – Oct 25, 2026")
      expect(errors).toEqual([])
    })
  }
  test("Sunday evening agrees on week, today and overdue state and advances on local midnight", async ({ page }) => {
    const errors: string[] = []
    page.on("pageerror", error => errors.push(error.message))
    page.on("console", message => { if (message.type() === "error") errors.push(message.text()) })
    // Monday UTC is still Sunday in New York. The SSR clock is intentionally different.
    await page.clock.setFixedTime(new Date("2026-10-19T03:30:00Z"))
    const response = await page.goto("/visual-regression/tasks?taskView=board&ssr=1", { waitUntil: "domcontentloaded" })
    expect(await response!.text()).toContain("Loading task calendar")
    const board = page.getByRole("region", { name: "Weekly task board", exact: true })
    await expect(board).toBeVisible({ timeout: 30000 })
    await expect(board.getByRole("heading", { level: 2 })).toHaveText("Oct 12 – Oct 18, 2026")
    await expect(page.locator('article[aria-label="Review last week’s outreach"]')).toContainText("Due Oct 19")
    await page.getByRole("button", { name: "Show weekend", exact: true }).click()
    await expect(page.getByRole("region", { name: "18 Sun", exact: true })).toHaveClass(/border-primary/)
    await page.getByRole("button", { name: "Next week", exact: true }).click()
    await page.getByRole("button", { name: "Today", exact: true }).click()
    await expect(page).toHaveURL(/taskWeek=2026-10-12/)
    await page.clock.setFixedTime(new Date("2026-10-19T04:05:00Z"))
    await page.evaluate(() => window.dispatchEvent(new Event("focus")))
    // An explicitly selected week stays put until Today is requested.
    await expect(board.getByRole("heading", { level: 2 })).toHaveText("Oct 12 – Oct 18, 2026")
    await page.getByRole("button", { name: "Today", exact: true }).click()
    await expect(page).toHaveURL(/taskWeek=2026-10-19/)
    await expect(page.getByRole("region", { name: "19 Mon", exact: true })).toHaveClass(/border-primary/, { timeout: 30000 })
    expect(errors.filter(message => /hydration|hydrated|didn't match/i.test(message))).toEqual([])
  })
})
