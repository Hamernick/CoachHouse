import { expect, test, type Page, type Locator } from "@playwright/test"
import { buildRichTextEditabilityFixture } from "./fixtures/rich-text-editability"

test("connected editor accepts typing and respects later read-only changes", async ({ page }) => {
  await page.setContent('<div id="root"></div>')
  await page.addScriptTag({ content: await buildRichTextEditabilityFixture() })
  const editor = page.getByLabel("Document", { exact: true })
  const updates = page.locator("output")
  const toggle = page.getByRole("button", { name: "Toggle access" })
  await expect(editor).toHaveAttribute("contenteditable", "false")
  await toggle.click()
  await expect(editor).toHaveAttribute("contenteditable", "true")
  await expect(updates).toHaveText("0")
  await editor.press("End")
  await editor.pressSequentially(" edited")
  await expect(editor).toHaveText("Existing text edited")
  const afterTyping = await updates.textContent()
  expect(Number(afterTyping)).toBeGreaterThan(0)
  await toggle.click()
  await expect(editor).toHaveAttribute("contenteditable", "false")
  await expect(updates).toHaveText(afterTyping!)
  await toggle.click()
  await expect(editor).toHaveAttribute("contenteditable", "true")
  await expect(editor).toHaveText("Existing text edited")
  await expect(updates).toHaveText(afterTyping!)
})


test("image alt text saves without replacing the source and survives editor reload", async ({ page }) => {
  await page.setContent('<div id="root"></div>')
  await page.addScriptTag({ content: await buildRichTextEditabilityFixture('<p>Photo</p><img src="https://example.org/photo.jpg" alt="Before">') })
  await page.getByRole("button", { name: "Toggle access" }).click()
  await page.getByAltText("Before", { exact: true }).click()
  await page.getByRole("button", { name: "Image options" }).click()
  await page.getByRole("menuitem", { name: "Edit image" }).click()
  await page.getByLabel("Alt text", { exact: true }).fill("Volunteers packing food")
  await page.getByRole("button", { name: "Save alt text" }).click()
  await expect(page.getByTestId("saved-html")).toContainText('alt="Volunteers packing food"')
  await page.getByRole("button", { name: "Reload editor" }).click()
  await expect(page.getByAltText("Volunteers packing food")).toHaveAttribute("src", "https://example.org/photo.jpg")
})


async function tabTo(page: Page, target: Locator) {
  for (let step = 0; step < 48; step++) {
    await page.keyboard.press("Tab")
    if (await target.evaluate(element => element === document.activeElement)) return
  }
  await expect(target).toBeFocused()
}

test("image controls support keyboard editing, native upload and read-only transitions", async ({ page }) => {
  await page.route("https://example.org/*.jpg", route => route.fulfill({ contentType: "image/svg+xml", body: '<svg xmlns="http://www.w3.org/2000/svg" width="320" height="80"><rect width="320" height="80" fill="gray"/></svg>' }))
  await page.setContent('<div id="root"></div>')
  await page.addScriptTag({ content: await buildRichTextEditabilityFixture('<p>Photo</p><img src="https://example.org/photo.jpg" alt="Before">') })
  const updates = page.locator("output")
  const toggle = page.getByRole("button", { name: "Toggle access" })
  const options = page.getByRole("button", { name: "Image options" })
  await expect(page.getByAltText("Before")).toBeVisible()
  await expect(updates).toHaveText("0")
  await expect(options).toHaveCount(0)
  await toggle.click()
  await tabTo(page, options)
  await expect(options.locator("..")).toHaveCSS("opacity", "1")
  await expect(options).toHaveCSS("outline-width", "2px")
  await page.keyboard.press("Enter")
  await expect(page.getByRole("menuitem", { name: "Edit Caption" })).toBeFocused()
  await page.keyboard.press("ArrowDown")
  const edit = page.getByRole("menuitem", { name: "Edit image" })
  await expect(edit).toBeFocused()
  await page.keyboard.press("Enter")
  const dialog = page.getByRole("dialog", { name: "Edit image" })
  const choose = dialog.getByRole("button", { name: "Choose Image" })
  await expect(choose).toBeFocused()
  await page.screenshot({ path: test.info().outputPath("image-edit-dialog.png"), animations: "disabled" })
  const chooserEvent = page.waitForEvent("filechooser")
  await page.keyboard.press("Enter")
  const chooser = await chooserEvent
  expect(chooser.isMultiple()).toBe(false)
  await chooser.setFiles([])
  await page.keyboard.press("Tab")
  await expect(dialog.getByLabel("Image URL", { exact: true })).toBeFocused()
  await page.keyboard.press("Tab")
  const alt = dialog.getByLabel("Alt text", { exact: true })
  await expect(alt).toBeFocused()
  await alt.fill("Volunteers packing food")
  await page.keyboard.press("Tab")
  await expect(dialog.getByRole("button", { name: "Save alt text" })).toBeFocused()
  await page.keyboard.press("Enter")
  await expect(dialog).toHaveCount(0)
  await expect(options).toBeFocused()
  await expect(page.getByTestId("saved-html")).toContainText('alt="Volunteers packing food"')
  await page.keyboard.press("Enter")
  await expect(page.getByRole("menuitem", { name: "Edit Caption" })).toBeFocused()
  await page.keyboard.press("Enter")
  const captionInput = page.getByRole("textbox", { name: "Image caption" })
  await expect(captionInput).toBeFocused()
  await captionInput.fill("Community volunteers")
  await page.keyboard.press("Enter")
  await expect(page.getByRole("button", { name: "Edit image caption" })).toBeFocused()
  await expect(page.getByTestId("saved-html")).toContainText('caption="Community volunteers"')
  const afterCaption = await updates.textContent()
  await page.keyboard.press("Enter")
  await captionInput.fill("Discard this caption")
  await page.keyboard.press("Escape")
  await expect(page.getByRole("button", { name: "Edit image caption" })).toBeFocused()
  await expect(page.getByTestId("saved-html")).not.toContainText("Discard this caption")
  await expect(updates).toHaveText(afterCaption!)
  await tabTo(page, options)
  await page.keyboard.press("Enter")
  await expect(page.getByRole("menuitem", { name: "Edit Caption" })).toBeFocused()
  await page.keyboard.press("ArrowDown")
  await expect(page.getByRole("menuitem", { name: "Edit image" })).toBeFocused()
  await page.keyboard.press("ArrowDown")
  await expect(page.getByRole("menuitem", { name: "Full Width" })).toBeFocused()
  await page.keyboard.press("Enter")
  await expect(page.getByTestId("saved-html")).toContainText(/width="[0-9]+"/)
  const afterEditing = await updates.textContent()
  await toggle.click()
  await expect(options).toHaveCount(0)
  await expect(page.getByRole("button", { name: /image caption/ })).toHaveCount(0)
  await expect(updates).toHaveText(afterEditing!)
})


test("keyboard file selection replaces only the selected image", async ({ page }) => {
  await page.route("https://example.org/*.jpg", route => route.fulfill({ contentType: "image/svg+xml", body: '<svg xmlns="http://www.w3.org/2000/svg" width="320" height="80"><rect width="320" height="80" fill="gray"/></svg>' }))
  await page.setContent('<div id="root"></div>')
  await page.addScriptTag({ content: await buildRichTextEditabilityFixture('<img src="https://example.org/first.jpg" alt="First"><img src="https://example.org/second.jpg" alt="Second">') })
  await page.getByRole("button", { name: "Toggle access" }).click()
  await page.getByAltText("Second", { exact: true }).hover()
  await page.getByRole("button", { name: "Image options" }).nth(1).click()
  await page.getByRole("menuitem", { name: "Edit image" }).click()
  const choose = page.getByRole("button", { name: "Choose Image" })
  await expect(choose).toBeFocused()
  const picker = page.waitForEvent("filechooser")
  await page.keyboard.press("Enter")
  await (await picker).setFiles({ name: "replacement.png", mimeType: "image/png", buffer: Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jD1sAAAAASUVORK5CYII=", "base64") })
  await expect(page.getByRole("dialog")).toHaveCount(0)
  await expect(page.getByAltText("First", { exact: true })).toHaveAttribute("src", "https://example.org/first.jpg")
  await expect(page.getByAltText("Second", { exact: true })).toHaveAttribute("src", "https://example.org/photo.jpg")
  await page.getByRole("button", { name: "Reload editor" }).click()
  await expect(page.getByAltText("Second", { exact: true })).toHaveAttribute("src", "https://example.org/photo.jpg")
})
