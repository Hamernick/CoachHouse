import { expect, test } from "@playwright/test"

const tasks = "/visual-regression/tasks?taskWeek=2026-10-19&filterPreview=1"
const projects = "/visual-regression/project-directory?view=list"
test.use({ extraHTTPHeaders: { "x-coach-house-visual-regression": "1" } })

for (const width of [1440, 390]) {
  test(`task relationships combine and live checkboxes persist (${width})`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto(tasks, { waitUntil: "domcontentloaded" })
    await page.getByRole("button", { name: /^Task relationship:/ }).click()
    await page.getByRole("checkbox", { name: "Proposed to me", exact: true }).click()
    await page.getByRole("checkbox", { name: "Collaborating", exact: true }).click()
    await expect(page.getByRole("checkbox", { name: "Assigned to me", exact: true })).toBeChecked()
    await expect(page.getByRole("checkbox", { name: "Proposed to me", exact: true })).toBeChecked()
    await page.keyboard.press("Escape")
    await expect(page.getByRole("button", { name: "Edit Proposed outreach task", exact: true })).toHaveCount(1)
    await expect(page.getByRole("button", { name: "Edit Collaborating on completed report", exact: true })).toBeVisible()
    await page.reload({ waitUntil: "domcontentloaded" })
    await expect(page.getByRole("button", { name: "Task relationship: 3 relationships", exact: true })).toBeVisible()
    await page.getByRole("button", { name: "Filter", exact: true }).click()
    await page.getByRole("checkbox", { name: "Done", exact: true }).click()
    await expect(page.getByRole("button", { name: "Edit Proposed outreach task", exact: true })).toHaveCount(0)
    await expect(page.getByRole("button", { name: "Edit Collaborating on completed report", exact: true })).toHaveCount(1)
    await page.getByRole("checkbox", { name: "To do", exact: true }).click()
    await expect(page.getByRole("checkbox", { name: "Done", exact: true })).toBeChecked()
    await expect(page.getByRole("button", { name: "Edit Proposed outreach task", exact: true })).toHaveCount(1)
    await testInfo.attach(`task-filters-${width}`, { body: await page.screenshot({ fullPage: true, path: testInfo.outputPath("filters.png") }), contentType: "image/png" })
    await page.keyboard.press("Escape")
    await page.reload({ waitUntil: "domcontentloaded" })
    await expect(page.getByRole("button", { name: "Edit Review the program budget", exact: true })).toHaveCount(0)
    await expect(page.getByRole("button", { name: "Edit Proposed outreach task", exact: true })).toHaveCount(1)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  })
}

test("task completion, ordering and board share the persisted selection", async ({ page }) => {
  await page.goto(tasks, { waitUntil: "domcontentloaded" })
  await page.getByRole("button", { name: "Task display options", exact: true }).click()
  await page.getByRole("combobox", { name: "Task ordering", exact: true }).click()
  await page.getByRole("option", { name: "Date added", exact: true }).click()
  await page.keyboard.press("Escape")
  const list = page.getByRole("list", { name: "Community program tasks", exact: true }).filter({ hasText: "Review the program budget" })
  await expect(list.getByRole("listitem").first()).toContainText("Review the program budget")
  await expect(page.getByRole("button", { name: /^Move .* (up|down)$/ })).toHaveCount(0)
  await page.reload({ waitUntil: "domcontentloaded" })
  await expect(list.getByRole("listitem").first()).toContainText("Review the program budget")
  await page.getByRole("button", { name: "Task display options", exact: true }).click()
  await page.getByRole("combobox", { name: "Task ordering", exact: true }).click()
  await page.getByRole("option", { name: "Due date", exact: true }).click()
  await page.getByRole("combobox", { name: "Completion", exact: true }).click()
  await page.getByRole("option", { name: "Not completed", exact: true }).click()
  await page.keyboard.press("Escape")
  await expect(list.getByRole("listitem").first()).toContainText("Review last week’s outreach")
  await page.getByRole("checkbox", { name: "Complete Confirm the community venue", exact: true }).click()
  await expect(page.getByRole("button", { name: "Edit Confirm the community venue", exact: true })).toHaveCount(0)
  await page.getByRole("button", { name: "Board", exact: true }).click()
  await expect(page.getByRole("article", { name: "Confirm the community venue", exact: true })).toHaveCount(0)
  await page.reload({ waitUntil: "domcontentloaded" })
  await expect(page.getByRole("article", { name: "Confirm the community venue", exact: true })).toHaveCount(0)
  await page.getByRole("button", { name: "Task display options", exact: true }).click()
  await page.getByRole("combobox", { name: "Completion", exact: true }).click()
  await page.getByRole("option", { name: "Completed", exact: true }).click()
  await page.keyboard.press("Escape")
  await expect(page.getByRole("article", { name: "Confirm the community venue", exact: true })).toBeVisible()
})

for (const width of [1440, 390]) {
  test(`project completion, date ordering and checkbox selections survive refresh (${width})`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto(projects, { waitUntil: "domcontentloaded" })
    // The directory restores its URL view after hydration; wait for list dates.
    await expect(page.getByText("Oct 30, 2026", { exact: true })).toBeVisible()
    await page.getByRole("button", { name: "View", exact: true }).click()
    await page.getByRole("button", { name: "Manual", exact: true }).click()
    await page.getByRole("button", { name: "Date added", exact: true }).click()
    await expect(page.getByRole("button", { name: /^Open project / }).first()).toHaveAccessibleName("Open project Newest project")
    await page.getByRole("combobox", { name: "Completion", exact: true }).click()
    await page.getByRole("option", { name: "Completed", exact: true }).click()
    await page.keyboard.press("Escape")
    await expect(page.getByText("Newest project", { exact: true })).toBeVisible()
    await expect(page.getByText("Earlier project", { exact: true })).toHaveCount(0)
    await page.reload({ waitUntil: "domcontentloaded" })
    await expect(page.getByText("Earlier project", { exact: true })).toHaveCount(0)
    await page.getByRole("button", { name: "View", exact: true }).click()
    await page.getByRole("combobox", { name: "Completion", exact: true }).click()
    await page.getByRole("option", { name: "Not completed", exact: true }).click()
    await page.getByRole("button", { name: "Date added", exact: true }).click()
    await page.getByRole("dialog").filter({ has: page.getByRole("button", { name: "Alphabetical", exact: true }) }).getByRole("button", { name: "Due date", exact: true }).click()
    await page.keyboard.press("Escape")
    await expect(page.getByText("Newest project", { exact: true })).toHaveCount(0)
    await expect(page.getByText("Earlier project", { exact: true })).toBeVisible()
    await page.getByRole("button", { name: "Filter", exact: true }).click()
    await page.getByRole("checkbox", { name: "Active", exact: true }).click()
    await expect(page.getByText("Undated project", { exact: true })).toHaveCount(0)
    await page.getByRole("checkbox", { name: "Planned", exact: true }).click()
    await expect(page.getByRole("checkbox", { name: "Active", exact: true })).toBeChecked()
    await expect(page.getByText("Undated project", { exact: true })).toBeVisible()
    await testInfo.attach(`project-filters-${width}`, { body: await page.screenshot({ fullPage: true, path: testInfo.outputPath("filters.png") }), contentType: "image/png" })
    await page.keyboard.press("Escape")
    await page.reload({ waitUntil: "domcontentloaded" })
    await expect(page).toHaveURL(/order=date/)
    await expect(page.getByText("Newest project", { exact: true })).toHaveCount(0)
    await expect(page.getByText("Undated project", { exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  })
}
