for (const width of [1440, 390]) {
  test(`project sponsorship is optional and the add-tab menu stays reachable (${width})`, async ({ page }) => {
    await page.setViewportSize({ width, height: 844 })
    await page.goto(fixture)
    const section = page.getByRole("region", { name: "Project tab review" })
    await expect(section.getByRole("checkbox", { name: "Add Fiscal Sponsorship" })).not.toBeChecked()
    await section.getByRole("checkbox", { name: "Add Fiscal Sponsorship" }).check()
    await expect(section.getByRole("checkbox", { name: "Add Fiscal Sponsorship" })).toBeChecked()
    await expect(section.getByRole("tab", { name: "Fiscal Sponsorship", exact: true })).toHaveCount(0)
    const add = section.getByRole("button", { name: "Add project tab" })
    await add.scrollIntoViewIfNeeded()
    const bounds = await add.boundingBox()
    expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(width)
    await add.click()
    await page.getByRole("menuitem", { name: "Fiscal Sponsorship", exact: true }).click()
    await expect(section.getByRole("tab", { name: "Fiscal Sponsorship", exact: true })).toHaveAttribute("aria-selected", "true")
    await expect(section.getByRole("tabpanel")).toContainText("Sample sponsorship tab added")
    const list = section.getByRole("tablist")
    expect(await list.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
    const activeTab = section.getByRole("tab", { name: "Fiscal Sponsorship", exact: true })
    await expect.poll(() => activeTab.evaluate((element) => getComputedStyle(element, "::after").opacity)).toBe("1")
    await section.getByRole("tab", { name: "Tasks", exact: true }).click()
    await expect(section.getByRole("tab", { name: "Tasks", exact: true })).toHaveAttribute("aria-selected", "true")
    await expect.poll(() => activeTab.evaluate((element) => getComputedStyle(element, "::after").opacity)).toBe("0")
    expect(await section.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
    await add.click()
    await expect(page.getByRole("menuitem", { name: "Fiscal Sponsorship (added)", exact: true })).toBeDisabled()
    await page.keyboard.press("Escape")
    await expect(add).toBeFocused()
  })
}


test("organization programs open the saved builder without autosaving on view", async ({ page }) => {
  const writes: string[] = []
  // Block every mutation during this read-only review, including regressions.
  await page.route("**/*", async (route) => {
    if (route.request().method() !== "GET" && route.request().method() !== "HEAD") {
      if (route.request().headers()["next-action"]) writes.push(route.request().url())
      await route.abort()
    } else await route.continue()
  })
  await page.goto(fixture)
  const section = page.getByRole("region", { name: "Organization programs review" })
  await section.getByRole("tab", { name: "Programs", exact: true }).click()
  await expect(section.getByText("Community mentorship", { exact: true })).toBeVisible()
  await section.getByRole("button", { name: "View / edit" }).click()
  const dialog = page.getByRole("dialog", { name: "Activity builder" })
  await expect(dialog).toBeVisible()
  await dialog.getByRole("button", { name: "Continue", exact: true }).click()
  await expect(dialog.getByLabel("Activity name", { exact: true })).toHaveValue("Community mentorship")
  // The existing autosave debounce is 700ms; reading must never trigger it.
  await page.waitForTimeout(1000)
  expect(writes).toEqual([])
  await dialog.getByRole("button", { name: "Cancel", exact: true }).click()
  await expect(dialog).toBeHidden()
})
