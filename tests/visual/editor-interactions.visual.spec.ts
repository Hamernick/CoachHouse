import { expect, test } from "@playwright/test"

// These interaction assertions also run against the existing dev server on macOS;
// screenshot comparisons still use the guarded repository visual config in CI.
const fixture = `${process.env.PLAYWRIGHT_BASE_URL ?? ""}/visual-regression/project-feedback?scenario=editors`
test.use({ extraHTTPHeaders: { "x-coach-house-visual-regression": "1" } })

for (const width of [1440, 390]) {
  test(`task opens above a scrolled transformed list and restores focus (${width})`, async ({ page }) => {
    await page.setViewportSize({ width, height: 844 })
    await page.goto(fixture)
    const list = page.getByTestId("task-list-scroll")
    await list.evaluate((element) => { element.scrollTop = 500 })
    const opener = page.getByRole("button", { name: "Open task", exact: true })
    await opener.click()
    const dialog = page.getByRole("dialog", { name: "Edit task" })
    await expect(dialog.locator("#task-create-title")).toHaveValue("Review staff meeting structure")
    const bounds = await dialog.boundingBox()
    expect(bounds!.y).toBeGreaterThanOrEqual(15)
    expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(829)
    expect(bounds!.x).toBeGreaterThanOrEqual(15)
    expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(width - 15)
    await dialog.getByRole("button", { name: "To do", exact: true }).click()
    await page.getByRole("option", { name: "In progress", exact: true }).click()
    await dialog.getByRole("button", { name: "Assignee" }).click()
    await page.getByRole("option", { name: "Sample reviewer" }).click()
    await expect(dialog.getByRole("button", { name: "Sample reviewer" })).toBeVisible()
    await dialog.getByRole("button", { name: "Start date", exact: true }).click()
    await expect(page.locator('[data-slot="calendar"]')).toBeVisible()
    await page.keyboard.press("Escape")
    await expect(dialog).toBeVisible()
    await dialog.locator("#task-create-title").fill("Reviewed sample task")
    await dialog.getByRole("button", { name: "Save changes", exact: true }).click()
    await expect(dialog).toBeHidden()
    await expect(page.getByRole("status").filter({ hasText: "Task saved" })).toBeVisible()
    await expect(opener).toBeFocused()
    await expect.poll(() => list.evaluate((element) => element.scrollTop)).toBe(500)
    await opener.click()
    await expect(dialog.locator("#task-create-title")).toHaveValue("Reviewed sample task")
    await expect(dialog.getByRole("button", { name: "In progress", exact: true })).toBeVisible()
    await page.keyboard.press("Escape")
    await expect(dialog).toBeHidden()
    await expect(opener).toBeFocused()
    await expect.poll(() => page.locator("body").evaluate((element) => getComputedStyle(element).pointerEvents)).not.toBe("none")
  })

  for (const title of ["Mission", "Vision"]) {
    test(`${title} supports wheel and keyboard scrolling without losing controls (${width})`, async ({ page }) => {
      await page.setViewportSize({ width, height: 844 })
      await page.route("**/api/account/document-capabilities?organizationId=sample", (route) =>
        route.fulfill({
          json: { capabilities: { canView: true, canViewHistory: true, canEdit: true, reason: "editable" } },
        }),
      )
      await page.goto(fixture)
      await page.getByRole("button", { name: `Open ${title}`, exact: true }).click()
      const dialog = page.getByRole("dialog", { name: title, exact: true })
      const editor = dialog.locator(".ProseMirror")
      await expect(editor).toHaveAttribute("contenteditable", "true")
      await expect(editor).toContainText(`${title} paragraph 70`)
      const original = await editor.innerHTML()
      const scroller = dialog.locator(".overflow-y-auto").first()
      const bounds = await scroller.boundingBox()
      await page.mouse.move(bounds!.x + bounds!.width / 2, bounds!.y + bounds!.height / 2)
      await page.mouse.wheel(0, 650)
      await expect.poll(() => scroller.evaluate((element) => element.scrollTop)).toBeGreaterThan(100)
      const before = await scroller.evaluate((element) => element.scrollTop)
      await page.mouse.wheel(0, -300)
      await expect.poll(() => scroller.evaluate((element) => element.scrollTop)).toBeLessThan(before)
      const save = dialog.getByRole("button", { name: "Save document", exact: true })
      await expect(save).toBeInViewport()
      await expect(save).toBeDisabled()
      await editor.focus()
      await expect(editor).toBeFocused()
      await page.keyboard.press(process.platform === "darwin" ? "Meta+ArrowDown" : "Control+End")
      await expect(editor.locator("p").last()).toBeInViewport()
      await page.keyboard.insertText(" Temporary review edit.")
      await expect(save).toBeEnabled()
      await save.focus()
      await expect(save).toBeFocused()
      await expect(save).toBeInViewport()
      page.once("dialog", (confirmation) => confirmation.accept())
      await dialog.getByRole("button", { name: "Cancel", exact: true }).click()
      await expect(dialog).toBeHidden()
      await page.getByRole("button", { name: `Open ${title}`, exact: true }).click()
      await expect(editor).toContainText(`${title} paragraph 70`)
      expect(await editor.innerHTML()).toBe(original)
      await dialog.getByRole("button", { name: "Cancel", exact: true }).click()
    })
  }
}

