import { expect, test } from "@playwright/test"
import { buildDocumentCollaborationLifecycleFixture } from "./fixtures/document-collaboration-lifecycle"

test("actual editor remains editable without presence and recovers an unsaved draft after remount", async ({ page }) => {
  await page.route("http://127.0.0.1:3139/fixture", route => route.fulfill({ contentType: "text/html", body: '<meta charset="utf-8"><div id="root"></div>' }))
  await page.goto("http://127.0.0.1:3139/fixture")
  await page.addScriptTag({ content: await buildDocumentCollaborationLifecycleFixture() })
  const editor = page.getByLabel("Origin Story", { exact: true })
  await expect(editor).toHaveAttribute("contenteditable", "true")
  await expect(page.getByText("Live cursors unavailable")).toBeVisible()
  await page.getByRole("button", { name: "Disconnect test connection" }).click()
  await editor.press("End")
  await editor.pressSequentially(" retained draft")
  await expect(page.getByText("Connection interrupted. Your local copy is retained.")).toBeVisible()
  await page.getByRole("button", { name: "Close test editor" }).click()
  await page.getByRole("button", { name: "Restore test connection" }).click()
  await page.getByRole("button", { name: "Open test editor" }).click()
  await expect(page.getByRole("button", { name: "Restore earlier draft" })).toBeEnabled()
  await page.getByRole("button", { name: "Restore earlier draft" }).click()
  await expect(editor).toContainText("retained draft")
  await expect(page.getByText("Saved", { exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Revoke test access" }).click()
  await expect(editor).toHaveAttribute("contenteditable", "false")
  await expect(editor).toContainText("retained draft")
})

for (const existingSession of [false, true]) {
  test(`replacement paste persists with existing session ${existingSession}`, async ({ page }) => {
    const errors: string[] = []
    page.on("pageerror", error => errors.push(error.message))
    await page.route("http://127.0.0.1:3139/fixture", route => route.fulfill({ contentType: "text/html", body: '<meta charset="utf-8"><div id="root"></div>' }))
    await page.goto("http://127.0.0.1:3139/fixture")
    await page.addScriptTag({ content: await buildDocumentCollaborationLifecycleFixture(existingSession) })
    const editor = page.getByLabel("Origin Story", { exact: true })
    await expect(editor).toHaveAttribute("contenteditable", "true")
    await expect(page.getByText("Saved", { exact: true })).toBeVisible()
    await editor.press("ControlOrMeta+a")
    await editor.evaluate(element => {
      const clipboardData = new DataTransfer()
      clipboardData.setData("text/html", "<h2>Replacement vision.</h2><p>" + "Detailed community plans and outcomes. ".repeat(1000) + "</p><ul><li>Last pasted item.</li></ul>")
      element.dispatchEvent(new ClipboardEvent("paste", { clipboardData, bubbles: true, cancelable: true }))
    })
    await expect(editor).toContainText("Replacement vision.")
    await expect.poll(() => page.evaluate(() => (window as unknown as { savedDocument: () => string }).savedDocument())).toContain("Replacement vision.")
    await expect(page.getByText("Saved", { exact: true })).toBeVisible()
    await page.getByRole("button", { name: "Close test editor" }).click()
    await page.getByRole("button", { name: "Open test editor" }).click()
    await expect(editor).toContainText("Replacement vision.")
    await expect(editor).toContainText("Last pasted item.")
    const persisted = await page.evaluate(() => (window as unknown as { savedState: () => string }).savedState())
    await page.reload()
    await page.addScriptTag({ content: await buildDocumentCollaborationLifecycleFixture(existingSession, false, persisted) })
    await expect(editor).toContainText("Replacement vision.")
    await expect(editor).toContainText("Last pasted item.")
    await expect(page.getByText("Saved", { exact: true })).toBeVisible()
    expect(errors).toEqual([])
  })
}

test("switching immediately after paste waits for persistence; rejected saves stay open", async ({ page }) => {
  await page.route("http://127.0.0.1:3139/fixture", route => route.fulfill({ contentType: "text/html", body: '<meta charset="utf-8"><div id="root"></div>' }))
  await page.goto("http://127.0.0.1:3139/fixture")
  await page.addScriptTag({ content: await buildDocumentCollaborationLifecycleFixture(true) })
  const editor = page.getByLabel("Origin Story", { exact: true })
  await expect(editor).toHaveAttribute("contenteditable", "true")
  await editor.fill("Replacement awaiting save.")
  await page.getByRole("button", { name: "Save and switch section" }).click()
  await expect(editor).toHaveCount(0)
  expect(await page.evaluate(() => (window as unknown as { savedDocument: () => string }).savedDocument())).toContain("Replacement awaiting save.")
  await page.getByRole("button", { name: "Open test editor" }).click()
  await expect(editor).toContainText("Replacement awaiting save.")
  await page.getByRole("button", { name: "Disconnect test connection" }).click()
  await editor.fill("Unsaved offline replacement.")
  await page.getByRole("button", { name: "Save and switch section" }).click()
  await expect(page.getByText("Not saved", { exact: true })).toBeVisible()
  await expect(editor).toContainText("Unsaved offline replacement.")
})

test("a mismatched acknowledgement never reports Saved or removes the recovery copy", async ({ page }) => {
  await page.route("http://127.0.0.1:3139/fixture", route => route.fulfill({ contentType: "text/html", body: '<meta charset="utf-8"><div id="root"></div>' }))
  await page.goto("http://127.0.0.1:3139/fixture")
  await page.addScriptTag({ content: await buildDocumentCollaborationLifecycleFixture(true, true) })
  const editor = page.getByLabel("Origin Story", { exact: true })
  await expect(editor).toHaveAttribute("contenteditable", "true")
  await editor.fill("Do not acknowledge different content.")
  await expect(page.getByText("Not saved", { exact: true })).toBeVisible()
  await expect(editor).toContainText("Do not acknowledge different content.")
  expect(await page.evaluate(() => Object.values(localStorage).some(value => value.includes("Do not acknowledge different content.")))).toBe(true)
})

test("switching waits for newer edits made during an in-flight save", async ({ page }) => {
  await page.route("http://127.0.0.1:3139/fixture", route => route.fulfill({ contentType: "text/html", body: '<meta charset="utf-8"><div id="root"></div>' }))
  await page.goto("http://127.0.0.1:3139/fixture")
  await page.addScriptTag({ content: await buildDocumentCollaborationLifecycleFixture(true, false, "{}", 600) })
  const editor = page.getByLabel("Origin Story", { exact: true })
  await expect(editor).toHaveAttribute("contenteditable", "true")
  await editor.fill("First replacement.")
  await expect.poll(() => page.evaluate(() => (window as unknown as { savingRequests: number }).savingRequests)).toBe(1)
  await editor.fill("Newest replacement while saving.")
  await page.getByRole("button", { name: "Save and switch section" }).click()
  await expect(editor).toHaveCount(0)
  expect(await page.evaluate(() => (window as unknown as { savedDocument: () => string }).savedDocument())).toContain("Newest replacement while saving.")
  await page.getByRole("button", { name: "Open test editor" }).click()
  await expect(editor).toContainText("Newest replacement while saving.")
})
